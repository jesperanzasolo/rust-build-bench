"""Bazel (rules_rust, Bzlmod) configuration generator.

Pure functions: given the `cargo metadata` view of a workspace and the corpus
config, return ``{repo_relative_path: file_text}`` for MODULE.bazel, .bazelversion,
.bazelrc, the root BUILD.bazel, one BUILD.bazel per package directory and the
test-launcher script. Nothing here runs Bazel or touches the network.

The output is the standard rules_rust setup a Bazel user would write by hand:

* toolchains from the ``rust`` module extension, pinned to the corpus' Rust version;
* third-party crates from ``crate_universe`` (``crate.from_cargo`` over every member
  manifest and the workspace ``Cargo.lock``), consumed with ``all_crate_deps()`` /
  ``aliases()`` from ``@crates//:defs.bzl``;
* per package: ``rust_library``/``rust_proc_macro``, ``cargo_build_script``,
  ``rust_binary`` per bin, ``rust_test`` for unit tests (``crate = ...``) and one
  ``rust_test`` per integration-test target, ``cargo_toml_env_vars`` so every crate
  sees the same ``CARGO_PKG_*`` values Cargo would give it.

Two Cargo behaviours have no rules_rust attribute and are reproduced explicitly so
that the *same tests* pass under both tools (see METHODOLOGY.md):

* Cargo runs every test binary with the package directory as working directory.
  Bazel runs it from the runfiles root. ``--run_under=//:rbb_test_launcher`` changes
  into ``$CARGO_MANIFEST_DIR`` (which rules_rust sets, runfiles-relative) and makes
  the path-valued variables absolute first.
* insta locates snapshots via ``cargo metadata`` at run time; ``INSTA_WORKSPACE_ROOT``
  (insta's documented override) points it at the runfiles root instead.
"""

