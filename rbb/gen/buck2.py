def buckconfig(endpoint: str | None) -> str:
    lines = [HEADER, "# Cells and prelude as in buck2 examples/with_prelude.",
             "[cells]", "  root = .", "  prelude = prelude", "  toolchains = toolchains", "  none = none", "",
             "[cell_aliases]", "  config = prelude", "  ovr_config = prelude", "  fbcode = none",
             "  fbsource = none", "  fbcode_macros = none", "  buck = none", "",
             "[external_cells]", "  prelude = bundled", "",
             "[parser]",
             "  target_platform_detector_spec = target:root//...->prelude//platforms:default \\",
             "    target:prelude//...->prelude//platforms:default \\",
             "    target:toolchains//...->prelude//platforms:default", "",
             "[build]", "  execution_platforms = toolchains//:execution_platforms", "",
             "[project]", "  # Cargo's target dir, VCS data and Reindeer's cargo home are not sources.",
             f"  ignore = .git, target, {THIRD_PARTY}/.cargo", "",
             "[buck2]", "  digest_algorithms = SHA256"]
    if endpoint:
        lines += ["  # Rust compile and link actions leave cache upload to this default.",
                  "  default_allow_cache_upload = true", "",
                  "# REAPI cache (bazel-remote). Actions run locally; see toolchains/platforms.bzl.",
                  "[buck2_re_client]",
                  f"  engine_address = {endpoint}",
                  f"  action_cache_address = {endpoint}",
                  f"  cas_address = {endpoint}",
                  "  tls = false"]
    return "\n".join(lines) + "\n"


