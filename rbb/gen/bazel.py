def default_test_env(env: dict[str, str]) -> dict[str, str]:
    """Environment the tests of every tool see, minus what is Cargo/host-specific."""
    drop = {"PATH", "RUSTUP_HOME", "HOME"}
    return {k: v for k, v in env.items() if k not in drop and not k.startswith("CARGO_")}


def rust_dist_keys(rust_version: str, triples: list[str]) -> list[str]:
    """Archive names (sha256s keys) rules_rust downloads for `rust_version`."""
    return sorted(f"{tool}-{rust_version}-{t}.tar.xz" for t in triples for tool in RUST_DIST_TOOLS)


def generate(ws: Workspace, corpus: Corpus, *, rust_version: str, rules_rust_version: str,
             remote_cache: str | None, output_user_root: str, repository_cache: str,
             bazel_version: str = "9.3.0", host_triple: str = "x86_64-unknown-linux-gnu",
             rust_sha256s: dict[str, str] | None = None, test_env: dict[str, str] | None = None,
             default_ws: Workspace | None = None,
             cargo_bazel_lockfile: bool = True) -> tuple[dict[str, str], dict]:
    """Return ({repo_relative_path: text}, coverage).

    `ws` must be loaded WITHOUT excluding packages. `default_ws`, when given, is the
    same workspace resolved without the corpus' feature flags (`metadata_args`): it is
    what crate_universe resolves third-party crates against, so first-party features
    that would need a different third-party resolution are dropped (and reported).
    """
    members = ws.members()
    excluded = set(corpus.exclude_packages)
    ctx: dict = {
        "host_triple": host_triple,
        "lib_names": _lib_name_by_package(ws),
        "ws_dep_platforms": _ws_dep_platforms(ws),
        "lib_target": {p.name: p.name for p in members},
        "dropped_features": {},
        "filegroups": {},          # pkg dir -> {filegroup name: [globs]}
        "outside_labels": {},      # pkg name -> [labels]
        "extra_data_labels": {},   # pkg name -> [labels]
    }
    if default_ws is not None:
        for p in members:
            dp = default_ws.packages.get(p.name)
            extra = set(p.features) - set(dp.features if dp else [])
            bad = extra & _third_party_affecting_features(ws, p)
            if bad:
                ctx["dropped_features"][p.name] = sorted(bad)

    def owner_dir(repo_path: str) -> str:
        o = owning_package(ws, repo_path)
        return o.dir if o else "."

    for p in members:
        labels = []
        for path in files_read_outside_package(ws, p):
            od = owner_dir(path)
            rel = path if od == "." else posixpath.relpath(path, od)
            is_dir = (ws.root / path).is_dir()
            name = _fg_name(rel)
            ctx["filegroups"].setdefault(od, {})[name] = [_dir_glob(rel) if is_dir else rel]
            labels.append(_label(od, name))
        ctx["outside_labels"][p.name] = sorted(set(labels))
        # Corpus.extra_data: files a package's tests read from elsewhere in the repo.
        # A glob inside another package maps onto that package's rbb_all_files; a glob
        # outside every package gets its own filegroup in the root package.
        extra, loose = [], []
        for g in corpus.extra_data.get(p.name, []):
            od = owner_dir(g.split("*", 1)[0].rstrip("/") or ".")
            if od == ".":
                loose.append(g)
            elif od != p.dir:
                extra.append(_label(od, ALL_FILES))
        if loose:
            name = "rbb_extra_data_" + re.sub(r"[^A-Za-z0-9_]+", "_", p.name)
            ctx["filegroups"].setdefault(".", {})[name] = sorted(loose)
            extra.append(_label(".", name))
        ctx["extra_data_labels"][p.name] = sorted(set(extra))

    files: dict[str, str] = {}
    coverage = {"packages": len(members), "test_targets": 0, "build_targets": 0,
                "per_package": {}, "skipped": [], "dropped_features": ctx["dropped_features"],
                "not_emitted": ["doctests (nextest does not run them)",
                                "benches and examples (not run by `cargo test`/nextest by default)"]}
    root_pkg_build = None
    for p in members:
        text, cov = _package_build(ws, p, corpus, ctx)
        if p.dir == ".":
            root_pkg_build = text
        else:
            files[f"{p.dir}/BUILD.bazel"] = text
        tests = [t for t in cov["targets"] if t["kind"] == "rust_test"]
        coverage["test_targets"] += len(tests)
        coverage["build_targets"] += len(cov["targets"]) - len(tests)
        coverage["per_package"][p.name] = {"tests": [t["name"] for t in tests],
                                           "excluded": p.name in excluded}
        coverage["skipped"] += [{"package": p.name, **s} for s in cov["skipped"]]

    editions = Counter(t.edition for p in members for t in ([p.lib] if p.lib else []) + p.bins)
    edition = sorted(editions.items(), key=lambda kv: (-kv[1], kv[0]))[0][0] if editions else "2021"
    files["MODULE.bazel"] = module_bazel(
        ws, rust_version=rust_version, rules_rust_version=rules_rust_version,
        edition=edition, platform_triples=[host_triple], rust_sha256s=rust_sha256s,
        cargo_bazel_lockfile=CARGO_BAZEL_LOCKFILE if cargo_bazel_lockfile else None)
    files[".bazelversion"] = bazel_version + "\n"
    files[".bazelrc"] = bazelrc(
        output_user_root=output_user_root, repository_cache=repository_cache,
        remote_cache=remote_cache,
        test_env=test_env if test_env is not None else default_test_env(corpus.env))
    files["BUILD.bazel"] = _root_build(ws, ctx, root_pkg_build, cargo_bazel_lockfile)
    if root_pkg_build is not None:
        # The root package's filegroups for files other packages include.
        extra = _filegroup_rules(ctx["filegroups"].get(".", {}))
        if extra and not any(f'name = "{n}"' in files["BUILD.bazel"]
                             for n in ctx["filegroups"].get(".", {})):
            files["BUILD.bazel"] += "\n" + "\n".join(extra)
    files[LAUNCHER_SCRIPT] = launcher_script()
    return dict(sorted(files.items())), coverage
