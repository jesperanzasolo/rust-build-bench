def _features_of(ws: Workspace, pkg_id: str) -> list[str]:
    for n in (ws.raw.get("resolve") or {}).get("nodes", []):
        if n["id"] == pkg_id:
            return sorted(n.get("features", []))
    return []


def _dep_spec(an: Analysis, pkg_id: str, key: str) -> dict:
    p = an.by_id[pkg_id]
    spec: dict = {}
    if key != p["name"]:
        spec["package"] = p["name"]
    source = p.get("source")
    if source is None:
        rel = os.path.relpath(Path(p["manifest_path"]).parent, an.ws.root / THIRD_PARTY)
        spec["path"] = rel.replace(os.sep, "/")
    elif source.startswith("git+"):
        url, _, sha = source[len("git+"):].partition("#")
        spec["git"] = url.split("?", 1)[0]
        spec["rev"] = sha
    else:
        spec["version"] = "=" + p["version"]
        if source != _CRATES_IO:
            index = source.split("+", 1)[1] if "+" in source else source
            if source.startswith("sparse+"):
                index = source
            spec["registry-index"] = index
    spec["default-features"] = False
    feats = _features_of(an.ws, pkg_id)
    if feats:
        spec["features"] = feats
    return spec


def _workspace_manifest(ws: Workspace) -> dict:
    root = Path(ws.raw.get("workspace_root") or ws.root)
    try:
        return tomllib.loads((root / "Cargo.toml").read_text())
    except (OSError, tomllib.TOMLDecodeError):
        return {}


def third_party_manifest(an: Analysis) -> str:
    ws = an.ws
    lines = [HEADER.replace("# ", "# ", 1),
             "# A dummy package depending on every third-party dependency of every workspace",
             "# member at the exact resolved version and features. Reindeer vendors and",
             "# buckifies its dependency graph into third-party/BUCK.",
             "[workspace]", "",
             "[package]", f"name = {_tstr(DUMMY_PACKAGE)}", 'version = "0.0.0"',
             'edition = "2021"', "publish = false", "",
             "[[bin]]", 'name = "top"', 'path = "top/main.rs"', "",
             "[dependencies]"]
    for pid, key in sorted(an.tp_keys.items(), key=lambda kv: kv[1]):
        lines.append(f"{_tstr(key)} = {_tval(_dep_spec(an, pid, key))}")
    patch = _workspace_manifest(ws).get("patch") or {}
    for registry in sorted(patch):
        lines += ["", f"[patch.{_tstr(registry)}]"]
        for name in sorted(patch[registry]):
            spec = dict(patch[registry][name])
            if "path" in spec:
                abs_p = (Path(ws.raw.get("workspace_root") or ws.root) / spec["path"]).resolve()
                spec["path"] = os.path.relpath(abs_p, ws.root / THIRD_PARTY).replace(os.sep, "/")
            lines.append(f"{_tstr(name)} = {_tval(spec)}")
    return "\n".join(lines) + "\n"


