"""Run a test binary from its Cargo package directory, as `cargo test` does.

usage: cargo_test_runner.py <package dir relative to the project root> <test binary> [args...]
"""

import os
import sys


def main() -> None:
    pkg_dir, argv = sys.argv[1], sys.argv[2:]
    project_root = os.getcwd()  # buck2 runs tests from the project root
    exe = os.path.abspath(argv[0])
