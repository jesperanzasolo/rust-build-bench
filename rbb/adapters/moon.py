"""moon (moonrepo) v2: per-crate `test` tasks orchestrated by moon.

Configuration follows moon's Rust handbook, with one deliberate refinement: each
crate's `test` task declares its *transitive* workspace dependencies' sources as
inputs. Without that, a change in an upstream crate would not invalidate a cached
downstream test result, so moon would report stale passes. We give moon the most
correct configuration we can, then measure it.

The test command per crate is `cargo nextest run --workspace -E 'package(=<crate>)'`:
every task compiles the same workspace build (same packages, same feature
resolution), so the first task to take Cargo's build lock compiles it and every
other task finds it up to date and only runs its own crate's tests. An earlier
version used `-p <crate>`, which resolves features per crate, so shared
dependencies were rebuilt task after task while all tasks queued on the one lock
(run 2026-10-15: ruff did not finish in 3 hours).
"""

from __future__ import annotations

import json
import re
import shlex
from pathlib import Path

from .. import cargo_meta
from .base import TestRun, parse_nextest_counts, rm
from .cargo import CargoAdapter

ROOT_INPUTS = ["/Cargo.toml", "/Cargo.lock", "/rust-toolchain.toml", "/rust-toolchain",
               "/.cargo/**/*", "/.config/nextest.toml", "/build.rs"]


class MoonAdapter(CargoAdapter):
    name = "moon"
    family = "cargo-native"
    services = ("bazel-remote",)
    generated_paths = ("target/", ".moon/", "**/moon.yml", "moon.yml")

    def versions(self) -> dict[str, str]:
        v = super().versions()
        v["moon"] = self.ctx.capture(["moon", "--version"]).strip()
        return v

    def env(self) -> dict[str, str]:
        return {"MOON_COLOR": "0", "MOON_TOOLCHAIN_FORCE_GLOBALS": "1"}

    # -- config generation ----------------------------------------------------
    def sync(self) -> None:
        ctx = self.ctx
        ws = cargo_meta.load(ctx.paths.ws, env=ctx.base_env(),
                             exclude=set(ctx.corpus.exclude_packages),
                             extra_args=ctx.corpus.metadata_args)
        ws_full = ws
        moon_dir = ctx.paths.ws / ".moon"
        moon_dir.mkdir(exist_ok=True)
        projects = {p.name: p.dir for p in ws.members()}
        endpoint = ctx.services.endpoints.get("bazel-remote-grpc") if ctx.services else None
        lines = ["# Generated by rust-build-bench. Do not edit.", "projects:"]
        lines += [f"  {json.dumps(n)}: {json.dumps(d)}" for n, d in sorted(projects.items())]
        lines += ["vcs:", "  client: 'git'", "  defaultBranch: 'main'"]
        if endpoint:
            lines += ["remote:", f"  host: '{endpoint}'", "  api: 'grpc'"]
        (moon_dir / "workspace.yml").write_text("\n".join(lines) + "\n")
        (moon_dir / "toolchains.yml").write_text(
            "# Generated by rust-build-bench. Rust from PATH (rustup), as in every other tool.\n"
            "rust: {}\n")
        for p in ws.members():
            # Project relationships follow normal and build dependencies only: Cargo
            # allows dev-dependency cycles (a test helper crate depending back on
            # the crate it tests), moon's project graph does not. Dev-dependency
            # sources still invalidate the test task through its inputs below.
            deps = sorted({d.package for d in p.ws_deps_of("normal", "build") if d.package in projects})
            inputs = [f"/{p.dir}/**/*" if p.dir != "." else "/src/**/*"]
            for dep in sorted(ws_full.transitive_ws_deps(p.name)):
                inputs.append(f"/{ws.packages[dep].dir}/**/*")
            inputs += ROOT_INPUTS
            inputs += [f"/{g}" for g in ctx.corpus.extra_data.get(p.name, [])]
            argv = self.nextest_argv(["--workspace", *self.exclude_args(), *self.filter_args(f"package(={p.name})")])
            doc = [
                "# Generated by rust-build-bench. Do not edit.",
                "language: 'rust'",
                f"dependsOn: {json.dumps(deps)}",
                "tasks:",
                "  test:",
                f"    command: {json.dumps(shlex.join(argv))}",
                "    inputs:",
                *[f"      - {json.dumps(i)}" for i in inputs],
                "    options:",
                "      cache: true",
                "      runInCI: true",
                "      runFromWorkspaceRoot: true",
                "      shell: true",
            ]
            (ctx.paths.ws / p.dir / "moon.yml").write_text("\n".join(doc) + "\n")

    # -- execution --------------------------------------------------------------
    def test(self, *, scenario, step, base, head) -> TestRun:
        if base is None:
            # `moon run` is `moon exec` with --on-failure=bail; CI semantics need continue.
            argv = ["moon", "exec", ":test", "--on-failure", "continue", "--summary", "detailed"]
        else:
            argv = ["moon", "ci", ":test", "--base", base, "--head", head]
        r = self.ctx.run(argv, scenario=scenario, step=step, env=self.env())
        counts = parse_nextest_counts(r.log_path)
        try:
            text = Path(r.log_path).read_text(errors="replace")
        except OSError:
            text = ""
        counts.update(self._report_counts(text))
        return TestRun(commands=[r], counts=counts)

    def _report_counts(self, log_text: str = "") -> dict:
        # Prefer the SUMMARY block moon prints ("pass RunTask(x:test) (cached, ...)").
        statuses: dict[str, int] = {}
        for m in re.finditer(r"^(pass|fail|skip)\s+RunTask\([^)]*\)\s*(\(([^)]*)\))?", log_text, re.M):
            s = "cached" if m.group(3) and "cached" in m.group(3) else m.group(1)
            statuses[s] = statuses.get(s, 0) + 1
        if statuses:
            return {"moon_tasks": statuses}
        for name in ("ciReport.json", "runReport.json"):
            f = self.ctx.paths.ws / ".moon" / "cache" / name
            if f.exists():
                try:
                    rep = json.loads(f.read_text())
                except Exception:
                    return {}
                statuses: dict[str, int] = {}
                for a in rep.get("actions", []):
                    if "RunTask" not in json.dumps(a.get("node", a.get("label", ""))):
                        continue
                    s = str(a.get("status", "unknown")).lower()
                    statuses[s] = statuses.get(s, 0) + 1
                f.unlink()
                return {"moon_tasks": statuses}
        return {}

    def wipe_local(self) -> None:
        super().wipe_local()
        rm(self.ctx.paths.ws / ".moon" / "cache")

    def state_dirs(self):
        return {"target": self.ctx.paths.ws / "target", "moon-cache": self.ctx.paths.ws / ".moon" / "cache"}
