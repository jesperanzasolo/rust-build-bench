def _label(pkg_dir: str, name: str) -> str:
    return f"//{'' if pkg_dir == '.' else pkg_dir}:{name}"


def _rel(path: str, pkg_dir: str) -> str:
    return path if pkg_dir == "." else os.path.relpath(path, pkg_dir).replace(os.sep, "/")


def _package_files(ws: Workspace, pkg: Package, member_dirs: list[str]) -> list[str]:
    """Files Buck2 considers part of `pkg`'s BUCK package (package-relative, sorted)."""
    base = ws.root / pkg.dir
    stop = {d for d in member_dirs if d != pkg.dir}
    out = []
    for dirpath, dirs, files in os.walk(base):
        rel_dir = os.path.relpath(dirpath, ws.root).replace(os.sep, "/")
        rel_dir = "" if rel_dir == "." else rel_dir
        keep = []
        for d in sorted(dirs):
            child = f"{rel_dir}/{d}" if rel_dir else d
            if child in stop or child in (".git", "target", "buck-out", THIRD_PARTY):
                continue
            if os.path.exists(os.path.join(dirpath, d, "BUCK")) and child not in member_dirs:
                continue
            keep.append(d)
        dirs[:] = keep
        for f in files:
            full = f"{rel_dir}/{f}" if rel_dir else f
            out.append(_rel(full, pkg.dir))
    return sorted(out)


@dataclasses.dataclass
class SrcSpec:
    include: list[str]
    exclude: list[str]


def _src_spec(root_rel: str, is_build_script: bool) -> SrcSpec:
    if "/" in root_rel:
        return SrcSpec([f"{root_rel.split('/')[0]}/**/*.rs"], [])
    if is_build_script:
        return SrcSpec(["**/*.rs"], ["benches/**", "examples/**", "src/**", "target/**", "tests/**"])
    return SrcSpec(["**/*.rs"], ["benches/**", "build.rs", "examples/**", "target/**", "tests/**"])


def _match(path: str, spec: SrcSpec) -> bool:
    def m(pat: str) -> bool:
        if pat.endswith("/**/*.rs"):
            return path.startswith(pat[: -len("**/*.rs")]) and path.endswith(".rs")
        if pat == "**/*.rs":
            return path.endswith(".rs")
        if pat.endswith("/**"):
            return path.startswith(pat[:-2])
        return path == pat
    return any(m(p) for p in spec.include) and not any(m(p) for p in spec.exclude)


def _scan_includes(ws: Workspace, pkg: Package, rs_files: list[str]) -> tuple[list[str], list[str], bool]:
    """(package-relative files included by include*! macros, repo-relative files outside
    the package, whether CARGO_MANIFEST_DIR appears in the sources)."""
    pkg_abs = (ws.root / pkg.dir).resolve()
    root_abs = ws.root.resolve()
    inside: set[str] = set()
    outside: set[str] = set()
    mentions = False
    for rel in rs_files:
        path = pkg_abs / rel
        try:
            text = path.read_text(errors="replace")
        except OSError:
            continue
        if "CARGO_MANIFEST_DIR" in text:
            mentions = True
        for m in _INCLUDE_RE.finditer(text):
            inc = m.group(1)
            if "CARGO_MANIFEST_DIR" in m.group(0):
                tgt = (pkg_abs / inc.lstrip("/")).resolve()
            else:
                tgt = (path.parent / inc).resolve()
            try:
                inside.add(str(tgt.relative_to(pkg_abs)).replace(os.sep, "/"))
                continue
            except ValueError:
                pass
            try:
                outside.add(str(tgt.relative_to(root_abs)).replace(os.sep, "/"))
            except ValueError:
                continue
    return sorted(inside), sorted(outside), mentions


def _harness_map(ws: Workspace, pkg: Package) -> dict[tuple[str, str], bool]:
    """{(kind, name): harness} from the package manifest ([lib], [[bin]], [[test]])."""
    try:
        man = tomllib.loads((ws.root / pkg.manifest).read_text())
    except (OSError, tomllib.TOMLDecodeError):
        return {}
    out = {}
    lib = man.get("lib") or {}
    if "harness" in lib:
        out[("lib", lib.get("name", pkg.name).replace("-", "_"))] = bool(lib["harness"])
    for kind in ("bin", "test"):
        for t in man.get(kind, []) or []:
            if "harness" in t and "name" in t:
                out[(kind, t["name"])] = bool(t["harness"])
    return out


def _cargo_env(pkg_raw: dict, pkg: Package, crate: str, manifest_dir: str) -> dict[str, str]:
    ver = pkg.version
    core, _, pre = ver.partition("-")
    core = core.split("+", 1)[0]
    parts = (core.split(".") + ["0", "0", "0"])[:3]
    env = {
        "CARGO_CRATE_NAME": crate,
        "CARGO_MANIFEST_DIR": manifest_dir,
        "CARGO_PKG_AUTHORS": ":".join(pkg_raw.get("authors") or []),
        "CARGO_PKG_DESCRIPTION": pkg_raw.get("description") or "",
        "CARGO_PKG_HOMEPAGE": pkg_raw.get("homepage") or "",
        "CARGO_PKG_LICENSE": pkg_raw.get("license") or "",
        "CARGO_PKG_LICENSE_FILE": pkg_raw.get("license_file") or "",
        "CARGO_PKG_NAME": pkg.name,
        "CARGO_PKG_README": pkg_raw.get("readme") or "",
        "CARGO_PKG_REPOSITORY": pkg_raw.get("repository") or "",
        "CARGO_PKG_RUST_VERSION": pkg_raw.get("rust_version") or "",
        "CARGO_PKG_VERSION": ver,
        "CARGO_PKG_VERSION_MAJOR": parts[0],
        "CARGO_PKG_VERSION_MINOR": parts[1],
        "CARGO_PKG_VERSION_PATCH": parts[2],
        "CARGO_PKG_VERSION_PRE": pre.split("+", 1)[0],
        "CARGO_PRIMARY_PACKAGE": "1",
    }
    return {k: v if k == "CARGO_MANIFEST_DIR" or v.startswith("$(location") else _arg(v)
            for k, v in env.items()}


def _features_ok(t: Target, features: list[str]) -> bool:
    fs = set(features)
    return all(f in fs for f in t.required_features if "/" not in f)


@dataclasses.dataclass
class BuckPackage:
    loads: set[str] = dataclasses.field(default_factory=set)
    rules: list[tuple[str, str]] = dataclasses.field(default_factory=list)   # (sort key, text)
    names: set[str] = dataclasses.field(default_factory=set)

    def add(self, kind: str, name: str, attrs: dict, order: int = 5) -> None:
        if name in self.names:
            raise ValueError(f"duplicate Buck target name {name!r}")
        self.names.add(name)
        self.rules.append((f"{order}:{name}", _rule(kind, name, attrs)))

    def text(self) -> str:
        out = [HEADER]
        if self.loads:
            out.append("")
            out.extend(sorted(self.loads))
        for _k, r in sorted(self.rules):
            out += ["", r]
        return "\n".join(out) + "\n"


def _owner_dir(ws: Workspace, path: str) -> str:
    owner = common.owning_package(ws, path)
    return owner.dir if owner else "."


def _export_label(pkgs: dict[str, BuckPackage], ws: Workspace, path: str) -> str:
    owner = _owner_dir(ws, path)
    name = "rbb-export-" + re.sub(r"[^A-Za-z0-9_.-]+", "_", path)
    bp = pkgs.setdefault(owner, BuckPackage())
    if name not in bp.names:
        bp.add("export_file", name, {"src": _rel(path, owner), "mode": "reference",
                                     "visibility": ["PUBLIC"]}, order=9)
    return _label(owner, name)


def generate(ws: Workspace, corpus, rust_version: str, endpoint: str | None, *,
             host_triple: str = DEFAULT_HOST_TRIPLE, host_cfg_text: str = DEFAULT_HOST_CFG,
             vendor_extra_srcs: dict[str, list[str]] | None = None,
             cc_tools: dict[str, str] | None = None
             ) -> tuple[dict[str, str], dict]:
    """Return ({repo-relative path: text}, coverage) for the whole Buck2 overlay.

    `ws` must be loaded without excluding packages. `third-party/Cargo.lock` in the
    result is only a seed (a copy of the workspace lockfile) that the adapter writes
    before running `reindeer vendor`; Reindeer then owns that file and
    `third-party/BUCK`.
    """
    host_cfg = parse_cfg(host_cfg_text)
    an = analyze(ws, host_cfg, host_triple)
    if any(p.dir == THIRD_PARTY or p.dir.startswith(THIRD_PARTY + "/") for p in ws.members()):
        raise ValueError(f"a workspace member lives under {THIRD_PARTY}/; cannot overlay Buck2")
    base_flags, pkg_flags, star_flags = profile_rustc_flags(ws)
    excluded = set(corpus.exclude_packages)
    skip_args = [a for s in corpus.skip_tests for a in ("--skip", s)]
    member_dirs = sorted(p.dir for p in ws.members())
    raw_by_name = {an.by_id[i]["name"]: an.by_id[i] for i in an.member_ids.values()}
    pkgs: dict[str, BuckPackage] = {".": BuckPackage()}
    cov = {"packages": 0, "libraries": 0, "binaries": 0, "build_scripts": [],
           "test_targets": 0, "test_targets_by_kind": {"lib": 0, "bin": 0, "test": 0},
           "skipped": [], "mapped_srcs_targets": [], "manifest_dir_filegroup_tests": [],
           "host_filtered_deps": an.filtered, "third_party_direct": len(an.tp_keys)}

    # Corpus.extra_data: extra files a package's tests read, declared as test resources.
    extra_data: dict[str, list[str]] = {}
    for name, globs in sorted(corpus.extra_data.items()):
        if name not in ws.packages:
            continue
        for i, g in enumerate(globs):
            owner = _owner_dir(ws, g.split("*", 1)[0].rstrip("/") or g)
            fg = f"rbb-extra-data-{_sanitize(name)}-{i}"
            pkgs.setdefault(owner, BuckPackage()).add(
                "filegroup", fg, {"srcs": _glob([_rel(g, owner)]), "copy": False,
                                  "visibility": ["PUBLIC"]}, order=9)
            extra_data.setdefault(name, []).append(_label(owner, fg))

    def dep_labels(name: str, kinds: set[str], self_lib: bool, pkg: Package):
        deps, named = [], {}
        if self_lib and pkg.lib:
            deps.append(_label(pkg.dir, pkg.name))
        for e in an.edges[name]:
            if not (e.kinds & kinds):
                continue
            if e.member:
                dpkg = ws.packages[e.package]
                if not dpkg.lib:
                    continue
                lbl = _label(dpkg.dir, dpkg.name)
            else:
                lbl = f"//{THIRD_PARTY}:{an.tp_keys[e.pkg_id]}"
            if e.extern != e.lib_crate:
                named[e.extern] = lbl
            else:
                deps.append(lbl)
        return sorted(set(deps)), dict(sorted(named.items()))

    for pkg in ws.members():
        cov["packages"] += 1
        bp = pkgs.setdefault(pkg.dir, BuckPackage())
        pkg_raw = raw_by_name[pkg.name]
        files = _package_files(ws, pkg, member_dirs)
        harness = _harness_map(ws, pkg)
        outside_pkg = common.files_read_outside_package(ws, pkg)
        extra_flags = list(pkg_flags.get(pkg.name, []))
        manifest_fg = f"{pkg.name}-manifest-dir"
        manifest_fg_needed = False
        bs_flags: list[str] = []
        bs_env: dict[str, str] = {}

        def sources(t: Target, is_bs: bool = False):
            root_rel = _rel(t.src_path, pkg.dir)
            if root_rel.startswith("../"):
                return None
            spec = _src_spec(root_rel, is_bs)
            rs = [f for f in files if _match(f, spec)]
            if root_rel not in rs:
                rs.append(root_rel)
            inside, outside, mentions = _scan_includes(ws, pkg, rs)
            return root_rel, spec, rs, inside, outside, mentions

        def src_attrs(t: Target, label: str, is_bs: bool = False):
            got = sources(t, is_bs)
            if got is None:
                return None
            root_rel, spec, rs, inside, target_outside, mentions = got
            # common.files_read_outside_package is authoritative for the package; a
            # target needs the files its own sources include.
            outside = [o for o in outside_pkg if o in target_outside]
            extra = [f for f in inside if f in files and not _match(f, spec)]
            attrs: dict = {}
            if outside and pkg.dir != ".":
                # include*! reaches outside the package. Lay the crate's files and the
                # outside files out as in the repository, file by file (a directory
                # symlink would break `..` in include paths), in a rust_filegroup owned
                # by the root package: the prelude remaps rustc paths relative to the
                # srcs owner's package, so file!() stays repo-relative, as with Cargo.
                mapped = {}
                for f in sorted(set(rs) | set(extra)):
                    full = f"{pkg.dir}/{f}"
                    mapped[_export_label(pkgs, ws, full)] = full
                for o in outside:
                    mapped[_export_label(pkgs, ws, o)] = o
                tree = f"rbb-srcs-{_sanitize(pkg.dir)}-{label.split(':', 1)[1]}"
                pkgs["."].loads.add('load("@prelude//rust:sources.bzl", "rust_filegroup")')
                pkgs["."].add("rust_filegroup", tree, {
                    "mapped_srcs": dict(sorted(mapped.items())), "visibility": ["PUBLIC"]}, order=8)
                attrs["srcs_filegroup"] = _label(".", tree)
                attrs["crate_root"] = f"{pkg.dir}/{root_rel}"
                cov["mapped_srcs_targets"].append(label)
                mdir = pkg.dir
            else:
                srcs = _glob(spec.include, spec.exclude)
                if extra:
                    srcs = Raw(f"{srcs} + {_fmt(sorted(extra), 4)}")
                attrs["srcs"] = srcs
                attrs["crate_root"] = root_rel
                mdir = "."
            return attrs, mdir, mentions

        # -- build script ---------------------------------------------------
        if pkg.build_script:
            t = pkg.build_script
            got = src_attrs(t, _label(pkg.dir, f"{pkg.name}-build-script-build"), is_bs=True)
            if got is not None:
                attrs, mdir, _ = got
                deps, named = dep_labels(pkg.name, {"build"}, False, pkg)
                env = _cargo_env(pkg_raw, pkg, "build_script_build", mdir)
                # Cargo compiles build scripts without the package's features (those
                # reach the script as CARGO_FEATURE_* at run time) or profile overrides.
                bp.add("rust_binary", f"{pkg.name}-build-script-build", {
                    **attrs, "crate": "build_script_build", "edition": t.edition,
                    "env": env, "deps": deps, "named_deps": named, "visibility": []}, order=1)
                run_env = {k: v for k, v in _cargo_env(pkg_raw, pkg, "x", ".").items()
                           if k.startswith("CARGO_PKG_") and k not in ("CARGO_PKG_NAME", "CARGO_PKG_VERSION")}
                if pkg.links:
                    run_env["CARGO_MANIFEST_LINKS"] = _arg(pkg.links)
                bp.loads.add('load("@prelude//rust:cargo_buildscript.bzl", "buildscript_run")')
                bp.add("buildscript_run", f"{pkg.name}-build-script-run", {
                    "package_name": pkg.name, "version": pkg.version,
                    "buildscript_rule": f":{pkg.name}-build-script-build",
                    "env": dict(sorted(run_env.items())), "features": pkg.features,
                    "manifest_dir": f":{manifest_fg}"}, order=1)
                manifest_fg_needed = True
                bs_flags = [f"@$(location :{pkg.name}-build-script-run[rustc_flags])"]
                bs_env = {"OUT_DIR": f"$(location :{pkg.name}-build-script-run[out_dir])"}
                cov["build_scripts"].append(pkg.name)
            else:
                cov["skipped"].append({"target": f"{pkg.name} build script", "reason": "crate root outside package"})

        def common_attrs(t: Target, crate: str, label: str, *, test: bool):
            got = src_attrs(t, label)
            if got is None:
                return None, False
            attrs, mdir, mentions = got
            env = _cargo_env(pkg_raw, pkg, crate, mdir)
            env.update(bs_env)
            use_fg = test and mentions
            if use_fg:
                env["CARGO_MANIFEST_DIR"] = f"$(location :{manifest_fg})"
            attrs.update({"crate": crate, "edition": t.edition, "env": dict(sorted(env.items())),
                          "features": pkg.features, "rustc_flags": extra_flags + bs_flags})
            return attrs, use_fg

        def add_test(t: Target, kind: str, wrapper: str, crate: str, deps_kinds: set[str], self_lib: bool,
                     extra_env: dict[str, str] | None = None, proc_macro: bool = False):
            nonlocal manifest_fg_needed
            label = _label(pkg.dir, wrapper)
            if pkg.name in excluded:
                cov["skipped"].append({"target": label, "reason": "package excluded by corpus"})
                return
            if not t.test:
                cov["skipped"].append({"target": label, "reason": "test = false"})
                return
            if not _features_ok(t, pkg.features):
                cov["skipped"].append({"target": label, "reason": "required-features not enabled"})
                return
            attrs, use_fg = common_attrs(t, crate, label, test=True)
            if attrs is None:
                cov["skipped"].append({"target": label, "reason": "crate root outside package"})
                return
            if use_fg:
                manifest_fg_needed = True
                cov["manifest_dir_filegroup_tests"].append(label)
            deps, named = dep_labels(pkg.name, deps_kinds, self_lib, pkg)
            framework = harness.get((kind, t.name if kind != "lib" else crate), True)
            if extra_env:
                attrs["env"] = dict(sorted({**attrs["env"], **extra_env}.items()))
            if proc_macro:
                attrs["rustc_flags"] = attrs["rustc_flags"] + ["--extern=proc_macro"]
            inner = f"{wrapper}-inner"
            # Resources are runtime inputs: the manifest-dir filegroup baked into the
            # binary by env!("CARGO_MANIFEST_DIR") must exist when the test runs, also
            # after the compile came from the cache.
            resources = list(extra_data.get(pkg.name, []))
            if use_fg:
                resources.append(f":{manifest_fg}")
            bp.add("rust_test", inner, {**attrs, "deps": deps, "named_deps": named,
                                        "framework": None if framework else False,
                                        "resources": sorted(resources),
                                        "labels": [INNER_TEST_LABEL]}, order=6)
            bp.loads.add('load("@toolchains//:cargo_test.bzl", "cargo_test")')
            bp.add("cargo_test", wrapper, {
                "test": f":{inner}", "manifest_dir": pkg.dir,
                "args": skip_args if framework else [], "labels": ["rust"]}, order=7)
            cov["test_targets"] += 1
            cov["test_targets_by_kind"][kind] += 1

        # -- library ---------------------------------------------------------
        if pkg.lib:
            t = pkg.lib
            crate = t.crate_name
            attrs, _ = common_attrs(t, crate, _label(pkg.dir, pkg.name), test=False)
            if attrs is None:
                cov["skipped"].append({"target": _label(pkg.dir, pkg.name), "reason": "crate root outside package"})
            else:
                deps, named = dep_labels(pkg.name, {"normal"}, False, pkg)
                if pkg.is_proc_macro:
                    attrs["proc_macro"] = True
                bp.add("rust_library", pkg.name, {**attrs, "deps": deps, "named_deps": named,
                                                  "visibility": ["PUBLIC"]}, order=2)
                cov["libraries"] += 1
                add_test(t, "lib", f"{pkg.name}-unittest", crate, {"normal", "dev"}, False,
                         proc_macro=pkg.is_proc_macro)

        # -- binaries ----------------------------------------------------------
        bin_exes: dict[str, str] = {}
        for t in sorted(pkg.bins, key=lambda b: b.name):
            label = _label(pkg.dir, f"{t.name}-bin")
            if not _features_ok(t, pkg.features):
                cov["skipped"].append({"target": label, "reason": "required-features not enabled"})
                continue
            attrs, _ = common_attrs(t, t.crate_name, label, test=False)
            if attrs is None:
                cov["skipped"].append({"target": label, "reason": "crate root outside package"})
                continue
            attrs["env"] = dict(sorted({**attrs["env"], "CARGO_BIN_NAME": _arg(t.name)}.items()))
            deps, named = dep_labels(pkg.name, {"normal"}, True, pkg)
            bp.add("rust_binary", f"{t.name}-bin", {**attrs, "deps": deps, "named_deps": named,
                                                    "visibility": ["PUBLIC"]}, order=3)
            cov["binaries"] += 1
            bin_exes[t.name] = f"$(location :{t.name}-bin)"
            add_test(t, "bin", f"{t.name}-bin-unittest", t.crate_name, {"normal", "dev"}, True,
                     extra_env={"CARGO_BIN_NAME": _arg(t.name)})

        # -- integration tests -------------------------------------------------
        exe_env = {f"CARGO_BIN_EXE_{n}": v for n, v in sorted(bin_exes.items())}
        for t in sorted(pkg.tests, key=lambda x: x.name):
            add_test(t, "test", f"{t.name}-test", t.crate_name, {"normal", "dev"}, True,
                     extra_env=exe_env)

        if manifest_fg_needed:
            bp.add("filegroup", manifest_fg, {
                "srcs": _glob(["**"], ["BUCK"]), "copy": False, "visibility": ["PUBLIC"]}, order=0)

    files_out: dict[str, str] = {}
    for d, bp in sorted(pkgs.items()):
        files_out["BUCK" if d == "." else f"{d}/BUCK"] = bp.text()
    files_out.update(toolchain_files(rust_version, base_flags, endpoint, cc_tools))
    files_out[".buckconfig"] = buckconfig(endpoint)
    files_out[".buckroot"] = ""
    files_out[f"{THIRD_PARTY}/Cargo.toml"] = third_party_manifest(an)
    files_out[f"{THIRD_PARTY}/top/main.rs"] = "// " + HEADER[2:] + "\nfn main() {}\n"
    files_out[f"{THIRD_PARTY}/reindeer.toml"] = reindeer_toml(host_triple)
    files_out[f"{THIRD_PARTY}/.gitignore"] = _THIRD_PARTY_GITIGNORE
    tp_flags = dict(pkg_flags)
    if star_flags:
        for p in ws.raw["packages"]:
            if p["id"] not in an.member_ids.values():
                tp_flags[p["name"]] = star_flags + tp_flags.get(p["name"], [])
    fixups = third_party_fixups(an, {n: f for n, f in tp_flags.items() if n not in an.member_ids},
                                vendor_extra_srcs)
    files_out.update(fixups)
    lock = (Path(ws.raw.get("workspace_root") or ws.root) / "Cargo.lock")
    if lock.exists():
        files_out[LOCK_SEED_PATH] = lock.read_text()
    cov["crates_with_fixups"] = sorted(p.split("/")[2] for p in fixups)
    cov["skipped"].sort(key=lambda s: s["target"])
    cov["build_scripts"].sort()
    cov["mapped_srcs_targets"].sort()
    cov["manifest_dir_filegroup_tests"].sort()
    cov["rust_version"] = rust_version
    cov["toolchain_rustc_flags"] = base_flags
    return dict(sorted(files_out.items())), cov


