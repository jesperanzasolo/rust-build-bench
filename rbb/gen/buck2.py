def _crate_src_dirs(crate_dir: Path, manifest: Path) -> tuple[str, ...]:
    """Directories (crate-relative, with trailing "/") holding the crate root of the lib
    or a bin. `extra_srcs` applies to those targets, not to the build script."""
    try:
        man = tomllib.loads(manifest.read_text(errors="replace"))
    except tomllib.TOMLDecodeError:
        return ("src/",)
    roots = []
    lib = man.get("lib") or {}
    roots.append(lib.get("path", "src/lib.rs"))
    for b in man.get("bin", []) or []:
        roots.append(b.get("path", f"src/bin/{b.get('name', '')}.rs"))
    out = set()
    for r in roots:
        d = os.path.dirname(r.replace(os.sep, "/"))
        out.add("" if d in ("", ".") else d + "/")
    return tuple(sorted(out))


def scan_vendor_includes(vendor_dir: Path) -> dict[str, list[str]]:
    """{package name: [manifest-relative files]} that vendored crates read with include*!
    and that `**/*.rs` under the crate root's directory does not already cover."""
    out: dict[str, set[str]] = {}
    if not vendor_dir.is_dir():
        return {}
    for crate_dir in sorted(vendor_dir.iterdir()):
        man = crate_dir / "Cargo.toml"
        if not man.is_file():
            continue
        try:
            name = tomllib.loads(man.read_text(errors="replace"))["package"]["name"]
        except (tomllib.TOMLDecodeError, KeyError, TypeError):
            continue
        root = crate_dir.resolve()
        src_dirs = _crate_src_dirs(crate_dir, man)
        for dirpath, dirs, files in os.walk(root):
            dirs.sort()
            for fn in sorted(files):
                if not fn.endswith(".rs"):
                    continue
                path = Path(dirpath) / fn
                try:
                    text = path.read_text(errors="replace")
                except OSError:
                    continue
                found = [((root / m.group(1).lstrip("/")) if "CARGO_MANIFEST_DIR" in m.group(0)
                          else (path.parent / m.group(1))) for m in _INCLUDE_RE.finditer(text)]
                for m in _PEST_GRAMMAR_RE.finditer(text):
                    found += [root / m.group(1), root / "src" / m.group(1)]
                for tgt in found:
                    tgt = tgt.resolve()
                    try:
                        rel = str(tgt.relative_to(root)).replace(os.sep, "/")
                    except ValueError:
                        continue
                    # `**/*.rs` under the crate root's directory (Reindeer's default
                    # srcs) already covers .rs files there; anything else is extra.
                    if tgt.is_file() and not (rel.endswith(".rs") and rel.startswith(src_dirs)):
                        out.setdefault(name, set()).add(rel)
    return {k: sorted(v) for k, v in sorted(out.items())}


_VER = re.compile(r"(\d+)(?:\.(\d+))?(?:\.(\d+))?")


def _req_is_broad(req: str) -> bool:
    """Does a Cargo version requirement span more than one semver-compatible lane?
    (Reindeer's deterministic resolver widens such requirements to the newest lane.)"""
    req = req.strip()
    if req in ("", "*"):
        return True
    if "," not in req:
        return req.lstrip().startswith((">", "*")) or req.rstrip().endswith("*")
    lo = hi = None
    for part in req.split(","):
        part = part.strip()
        m = re.match(r"(>=|>|<=|<|=|\^|~)?\s*(.*)", part)
        op, ver = m.group(1) or "^", m.group(2)
        v = _VER.match(ver)
        if not v:
            return True
        nums = tuple(int(x) if x is not None else 0 for x in v.groups())
        if op in (">=", ">"):
            lo = nums
        elif op in ("<", "<="):
            hi = nums
        else:
            return False
    if lo is None or hi is None:
        return True
    lane = lambda t: (t[0],) if t[0] else (0, t[1]) if t[1] else (0, 0, t[2])  # noqa: E731
    top = list(hi)
    if hi[1:] == (0, 0) and hi[0] > 0:
        top = [hi[0] - 1, 0, 0]
    elif hi[0] == 0 and hi[2] == 0 and hi[1] > 0:
        top = [0, hi[1] - 1, 0]
    return lane(lo) != lane(tuple(top))


def _lane(version: str) -> str:
    if "-" in version:
        return "=" + version
    nums = [int(x) for x in version.split("+", 1)[0].split(".")]
    if nums[0]:
        return f"^{nums[0]}"
    if nums[1]:
        return f"^0.{nums[1]}"
    return f"^0.0.{nums[2]}"


def resolver_narrowing(an: Analysis) -> dict[str, dict[str, dict[str, str]]]:
    """{parent package: {parent version: {dependency name in its Cargo.toml: narrow_to}}}
    pinning every broad registry requirement to the compatibility lane Cargo.lock chose,
    so Reindeer's resolver lands on the same versions as Cargo."""
    nodes = {n["id"]: n for n in (an.ws.raw.get("resolve") or {}).get("nodes", [])}
    out: dict[str, dict[str, dict[str, str]]] = {}
    for p in an.ws.raw["packages"]:
        resolved = [an.by_id[d["pkg"]] for d in nodes.get(p["id"], {}).get("deps", [])
                    if d["pkg"] in an.by_id]
        for dep in p.get("dependencies", []):
            if dep.get("kind") == "dev" or dep.get("path") or not _req_is_broad(dep.get("req", "")):
                continue
            if dep.get("source") and not str(dep["source"]).startswith(("registry+", "sparse+")):
                continue
            cands = [r for r in resolved if r["name"] == dep["name"]]
            if not cands:
                continue
            versions = sorted({r["version"] for r in cands})
            key = dep.get("rename") or dep["name"]
            out.setdefault(p["name"], {}).setdefault(p["version"], {})[key] = _lane(versions[-1])
    return {k: dict(sorted(v.items())) for k, v in sorted(out.items())}


def third_party_fixups(an: Analysis, package_flags: dict[str, list[str]],
                       extra_srcs: dict[str, list[str]] | None = None) -> dict[str, str]:
    """fixups/<crate>/fixups.toml for third-party crates that have a build script (run it,
    the generic best-effort choice), a Cargo profile override, or files read by include*!
    (from `scan_vendor_includes`)."""
    extra_srcs = extra_srcs or {}
    narrowing = resolver_narrowing(an)
    member_ids = set(an.member_ids.values())
    tp_pkgs: dict[str, list[dict]] = {}
    for p in an.ws.raw["packages"]:
        if p["id"] in member_ids:
            continue
        tp_pkgs.setdefault(p["name"], []).append(p)
    out: dict[str, str] = {}
    for name in sorted(tp_pkgs):
        versions = tp_pkgs[name]
        built = [p for p in versions if p["id"] in an.host_reachable]
        has_bs = any(any("custom-build" in t["kind"] for t in p["targets"]) for p in built)
        links = any(p.get("links") for p in built)
        flags = package_flags.get(name)
        extra = extra_srcs.get(name)
        narrow = narrowing.get(name, {})
        if not has_bs and not flags and not extra and not narrow:
            continue
        lines = [HEADER]
        if extra:
            lines += ["# Files read by include*! macros.", f"extra_srcs = {_tval(extra)}"]
        if flags:
            lines += ["# Cargo [profile] package override.", f"rustc_flags = {_tval(flags)}"]
        if has_bs:
            lines += ["# Generic choice: run the build script, as Cargo does."]
            if links:
                lines += ["# The crate declares `links`, so forward its native link directives.",
                          "[buildscript.run]", "rustc_link_lib = true", "rustc_link_search = true"]
            else:
                lines += ["buildscript.run = true"]
        if narrow:
            # Reindeer's deterministic resolver picks the newest compatibility lane of a
            # broad requirement (">=0.6, <0.8"); pin it to the lane Cargo.lock chose.
            # Unconditional when every version of this crate agrees, else per version
            # (`cfg(version = ...)` sections may carry resolver fixups).
            lines += ["", "# Broad requirements, narrowed to the lane Cargo.lock resolved."]
            per_version = [narrow.get(p["version"], {}) for p in versions]
            if all(m == per_version[0] for m in per_version):
                for dep, req in per_version[0].items():
                    lines += [f"[resolver.dependencies.{_tstr(dep)}]", f"narrow_to = {_tstr(req)}"]
            else:
                for ver in sorted(narrow):
                    for dep, req in narrow[ver].items():
                        lines += [f"['cfg(version = \"={ver}\")'.resolver.dependencies.{_tstr(dep)}]",
                                  f"narrow_to = {_tstr(req)}"]
        out[f"{THIRD_PARTY}/fixups/{name}/fixups.toml"] = "\n".join(lines) + "\n"
    return out


def lock_version_mismatches(ws: Workspace, lock_text: str) -> list[str]:
    """Third-party packages of the workspace resolve whose exact version is missing from
    the Reindeer lockfile (empty means versions are identical)."""
    try:
        lock = tomllib.loads(lock_text)
    except tomllib.TOMLDecodeError as e:
        return [f"unparseable lockfile: {e}"]
    have = {(p["name"], p["version"]) for p in lock.get("package", [])}
    members = set(ws.raw["workspace_members"])
    want = {(p["name"], p["version"]) for p in ws.raw["packages"] if p["id"] not in members}
    return sorted(f"{n} {v}" for n, v in want - have)


