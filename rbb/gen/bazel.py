def _manifest(ws: Workspace, pkg: Package) -> dict:
    try:
        return tomllib.loads((ws.root / pkg.manifest).read_text())
    except (OSError, tomllib.TOMLDecodeError):
        return {}


def _harness(manifest: dict) -> dict[tuple[str, str], bool]:
    """(kind, target name) -> harness flag for targets that declare one."""
    out: dict[tuple[str, str], bool] = {}
    lib = manifest.get("lib") or {}
    if "harness" in lib:
        out[("lib", "")] = bool(lib["harness"])
    for kind, key in (("bin", "bin"), ("test", "test")):
        for t in manifest.get(key, []) or []:
            if "harness" in t and "name" in t:
                out[(kind, t["name"])] = bool(t["harness"])
    return out


def _raw_packages(ws: Workspace) -> dict[str, dict]:
    return {p["id"]: p for p in ws.raw.get("packages", [])}


def _lib_name_by_package(ws: Workspace) -> dict[str, str]:
    """package name -> lib crate name (first matching package; versions rarely differ)."""
    out: dict[str, str] = {}
    for p in ws.raw.get("packages", []):
        for t in p.get("targets", []):
            if set(t.get("kind", [])) & {"lib", "rlib", "proc-macro", "dylib", "cdylib", "staticlib"}:
                out.setdefault(p["name"], t["name"].replace("-", "_"))
                break
    return out


_TRIPLE_CFG = {
    "x86_64-unknown-linux-gnu": {"target_arch": "x86_64", "target_os": "linux", "target_family": "unix",
                                 "target_env": "gnu", "target_vendor": "unknown",
                                 "target_pointer_width": "64", "target_endian": "little", "unix": True},
    "aarch64-unknown-linux-gnu": {"target_arch": "aarch64", "target_os": "linux", "target_family": "unix",
                                  "target_env": "gnu", "target_vendor": "unknown",
                                  "target_pointer_width": "64", "target_endian": "little", "unix": True},
}


def cfg_matches(expr: str, triple: str) -> bool:
    """Evaluate a Cargo `[target.'...']` key for `triple`. Unknown predicates count as
    true, so an unrecognised condition can only add (never drop) a dependency."""
    expr = expr.strip()
    if not expr.startswith("cfg("):
        return expr == triple
    facts = _TRIPLE_CFG.get(triple, {})
    toks = re.findall(r'"[^"]*"|[A-Za-z_][A-Za-z0-9_]*|[(),=]', expr[4:-1])
    pos = 0

    def parse():
        nonlocal pos
        tok = toks[pos]
        pos += 1
        if tok in ("all", "any", "not") and pos < len(toks) and toks[pos] == "(":
            pos += 1
            vals = []
            while toks[pos] != ")":
                vals.append(parse())
                if toks[pos] == ",":
                    pos += 1
            pos += 1
            if tok == "all":
                return all(vals)
            if tok == "any":
                return any(vals)
            return not vals[0]
        if pos < len(toks) and toks[pos] == "=":
            val = toks[pos + 1].strip('"')
            pos += 2
            if tok not in facts:
                return True
            return facts[tok] == val
        if tok in ("unix", "windows"):
            return bool(facts.get(tok, False)) if facts else True
        return tok not in ("test", "debug_assertions") if facts else True

    try:
        return bool(parse())
    except (IndexError, KeyError):
        return True


def _ws_dep_platforms(ws: Workspace) -> dict[tuple[str, str, str], list[str | None]]:
    """(package, dep package, kind) -> the `target` keys the edge is declared under."""
    by_id = _raw_packages(ws)
    out: dict[tuple[str, str, str], list[str | None]] = {}
    for node in (ws.raw.get("resolve") or {}).get("nodes", []):
        p = by_id.get(node["id"])
        if p is None:
            continue
        for d in node.get("deps", []):
            dp = by_id.get(d["pkg"])
            if dp is None:
                continue
            for dk in d.get("dep_kinds", []) or [{"kind": None, "target": None}]:
                key = (p["name"], dp["name"], dk.get("kind") or "normal")
                out.setdefault(key, []).append(dk.get("target"))
    return out


def _third_party_affecting_features(ws: Workspace, pkg: Package) -> set[str]:
    """Features of `pkg` whose expansion enables a third-party dependency or a
    third-party crate feature (`dep:x`, `x/f`, `x?/f`, implicit optional-dep features)."""
    raw = next((p for p in ws.raw.get("packages", []) if p["name"] == pkg.name
                and p["manifest_path"].endswith(pkg.manifest)), None)
    if raw is None:
        return set()
    table: dict[str, list[str]] = raw.get("features", {}) or {}
    first_party = set(ws.packages)
    deps = {}
    for d in raw.get("dependencies", []):
        deps[d.get("rename") or d["name"]] = d["name"]

    def third_party(name: str) -> bool:
        pkg_name = deps.get(name, name)
        return name in deps and pkg_name not in first_party

    memo: dict[str, bool] = {}

    def affects(f: str, stack: frozenset) -> bool:
        if f in memo:
            return memo[f]
        if f in stack:
            return False
        res = False
        if f not in table and third_party(f):
            res = True
        for entry in table.get(f, []):
            if entry.startswith("dep:"):
                res |= third_party(entry[4:])
            elif "/" in entry:
                res |= third_party(entry.split("/", 1)[0].rstrip("?"))
            elif entry in table:
                res |= affects(entry, stack | {f})
            else:
                res |= third_party(entry)
        memo[f] = res
        return res

    return {f for f in pkg.features if affects(f, frozenset())}


