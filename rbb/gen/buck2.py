def parse_cfg(text: str) -> dict[str, set[str]]:
    """Parse `rustc --print cfg` output into {key: {values}} ("" for bare names)."""
    out: dict[str, set[str]] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if "=" in line:
            k, v = line.split("=", 1)
            out.setdefault(k.strip(), set()).add(v.strip().strip('"'))
        else:
            out.setdefault(line, set()).add("")
    return out


_CFG_TOKEN = re.compile(r'\s*(?:(\()|(\))|(,)|(=)|"((?:[^"\\]|\\.)*)"|([A-Za-z_][A-Za-z0-9_]*))')


def _cfg_tokens(expr: str) -> list[tuple[str, str]]:
    toks, pos = [], 0
    while pos < len(expr):
        if expr[pos:].strip() == "":
            break
        m = _CFG_TOKEN.match(expr, pos)
        if not m:
            raise ValueError(f"bad cfg expression: {expr!r}")
        pos = m.end()
        if m.group(1):
            toks.append(("(", "("))
        elif m.group(2):
            toks.append((")", ")"))
        elif m.group(3):
            toks.append((",", ","))
        elif m.group(4):
            toks.append(("=", "="))
        elif m.group(5) is not None:
            toks.append(("str", m.group(5)))
        else:
            toks.append(("id", m.group(6)))
    return toks


def cfg_matches(target: str | None, host_cfg: dict[str, set[str]], host_triple: str) -> bool:
    """Does a Cargo dependency `target` (None, a triple, or `cfg(...)`) apply to the host?"""
    if not target:
        return True
    target = target.strip()
    if not target.startswith("cfg("):
        return target == host_triple
    toks = _cfg_tokens(target[len("cfg"):])
    pos = 0

    def expect(kind):
        nonlocal pos
        if pos >= len(toks) or toks[pos][0] != kind:
            raise ValueError(f"bad cfg expression: {target!r}")
        pos += 1

    def pred() -> bool:
        nonlocal pos
        kind, val = toks[pos]
        if kind != "id":
            raise ValueError(f"bad cfg expression: {target!r}")
        pos += 1
        if val in ("all", "any", "not") and pos < len(toks) and toks[pos][0] == "(":
            pos += 1
            vals = []
            while toks[pos][0] != ")":
                vals.append(pred())
                if toks[pos][0] == ",":
                    pos += 1
            pos += 1
            if val == "all":
                return all(vals)
            if val == "any":
                return any(vals)
            if len(vals) != 1:
                raise ValueError(f"bad cfg expression: {target!r}")
            return not vals[0]
        if pos < len(toks) and toks[pos][0] == "=":
            pos += 1
            kind2, s = toks[pos]
            if kind2 != "str":
                raise ValueError(f"bad cfg expression: {target!r}")
            pos += 1
            return s in host_cfg.get(val, set())
        return val in host_cfg

    expect("(")
    result = pred()
    expect(")")
    return result


