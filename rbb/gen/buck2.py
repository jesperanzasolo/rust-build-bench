"""Buck2 project generator: overlays a Buck2 build on a Cargo workspace.

The output follows Buck2's and Reindeer's own documentation and examples:

* `.buckconfig` / `.buckroot` / `toolchains/` follow `examples/with_prelude` (bundled
  prelude, `system_*` toolchains) and `examples/remote_execution/*` (`[buck2_re_client]`).
* The execution platform runs every action locally and reads/writes the REAPI action
  cache (`CommandExecutorConfig(local_enabled = True, remote_enabled = False,
  remote_cache_enabled = True, allow_cache_uploads = True)`). Buck2 uploads a locally
  executed action only if the action allows it; Rust compile actions express no
  preference, so `[buck2] default_allow_cache_upload = true` is required as well
  (see `buck2_action_impl/src/actions/impls/run.rs` and `executors/caching.rs`).
* Third-party crates are vendored and buckified by Reindeer from a generated dummy
  package (`third-party/Cargo.toml`, as in Reindeer's `examples/01-intro` and
  `03-complex-fixups`), seeded with the workspace `Cargo.lock` so versions stay
  identical.
* First-party packages get hand-written-style `rust_library` / `rust_binary` /
  `rust_test` rules. Cargo runs a test binary from its package directory with
  `CARGO_MANIFEST_DIR` set; `rust_test` always runs from the project root and has no
  `args`. A small wrapper rule (`toolchains//:cargo_test.bzl`) re-exposes each
  `rust_test`'s `ExternalRunnerTestInfo` with that working directory and the corpus
  `--skip` arguments, the same pattern the prelude uses in
  `python_needed_coverage_test`. The wrapped `rust_test` carries the label
  `INNER_TEST_LABEL`, which the adapter excludes so each test binary runs once.

Test results are never served from the cache in this mode: `rust_test` does not set
`supports_test_execution_caching`, and Buck2 never uploads locally executed test runs
(`buck2_test/src/orchestrator.rs`). Build actions (rustc, links, build scripts) are
cached.

Everything here is a pure function of its inputs (the workspace metadata plus files
read from the checkout). Output is sorted and deterministic.
"""

