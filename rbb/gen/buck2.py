_CARGO_TEST_BZL = '''{header}
# Runs a rust_test the way `cargo test` / `cargo nextest` run a test binary: from the
# package directory, with CARGO_MANIFEST_DIR (and INSTA_WORKSPACE_ROOT) set, passing
# libtest arguments such as `--skip`. rust_test always runs from the project root and
# has no `args` attribute, so this re-exposes its ExternalRunnerTestInfo, like
# prelude//python:python_needed_coverage_test.bzl does. The wrapped rust_test is
# labelled "{inner}" and excluded from `buck2 test` so it runs once.

def _cargo_test_impl(ctx: AnalysisContext) -> list[Provider]:
    inner = ctx.attrs.test[ExternalRunnerTestInfo]
    command = [cmd_args(ctx.attrs._runner[RunInfo]), ctx.attrs.manifest_dir] + list(inner.command) + ctx.attrs.args
    env = dict(inner.env)
    env.update(ctx.attrs.env)
    return [
        DefaultInfo(),
        RunInfo(args = cmd_args(command)),
        ExternalRunnerTestInfo(
            type = "rust",
            command = command,
            env = env,
            labels = ctx.attrs.labels,
            contacts = ctx.attrs.contacts,
            # Paths are absolute because the runner changes directory.
            run_from_project_root = True,
            use_project_relative_paths = False,
        ),
    ]

cargo_test = rule(
    impl = _cargo_test_impl,
    attrs = {{
        "args": attrs.list(attrs.string(), default = []),
        "contacts": attrs.list(attrs.string(), default = []),
        "env": attrs.dict(key = attrs.string(), value = attrs.arg(), default = {{}}),
        "labels": attrs.list(attrs.string(), default = []),
        "manifest_dir": attrs.string(),
        "test": attrs.dep(providers = [ExternalRunnerTestInfo]),
        "_runner": attrs.default_only(attrs.dep(providers = [RunInfo], default = "toolchains//:cargo_test_runner")),
    }},
)
'''

