_DEV_DEFAULTS = {"opt-level": 0, "debug": True, "debug-assertions": True,
                 "overflow-checks": True, "codegen-units": 256, "lto": False}


def _profile_flags(p: dict, *, profile_level: bool) -> list[str]:
    flags = []
    if "opt-level" in p:
        flags.append(f"-Copt-level={p['opt-level']}")
    if "debug" in p:
        d = p["debug"]
        if isinstance(d, bool):   # True == 1 as a dict key, so handle bools first
            level = "2" if d else "0"
        else:
            level = {"none": "0", "line-directives-only": "line-directives-only",
                     "line-tables-only": "line-tables-only", "limited": "1",
                     "full": "2"}.get(d, str(d))
        flags.append(f"-Cdebuginfo={level}")
    for key in ("debug-assertions", "overflow-checks"):
        if key in p:
            flags.append(f"-C{key}={'on' if p[key] else 'off'}")
    if "codegen-units" in p:
        flags.append(f"-Ccodegen-units={p['codegen-units']}")
    if "split-debuginfo" in p:
        flags.append(f"-Csplit-debuginfo={p['split-debuginfo']}")
    if "strip" in p and p["strip"] not in (False, "none"):
        flags.append(f"-Cstrip={'symbols' if p['strip'] is True else p['strip']}")
    if profile_level:
        lto = p.get("lto", False)
        if lto in (False, "false"):
            flags.append("-Cembed-bitcode=no")
        elif lto == "off":
            flags += ["-Clto=off", "-Cembed-bitcode=no"]
        elif lto in (True, "fat", "true"):
            flags.append("-Clto=fat")
        elif lto == "thin":
            flags.append("-Clto=thin")
    return flags


def profile_rustc_flags(ws: Workspace) -> tuple[list[str], dict[str, list[str]], list[str]]:
    """(toolchain flags, per-package override flags, "*" override flags) reproducing the
    Cargo `test` profile (which inherits `dev`) of the workspace."""
    prof = _workspace_manifest(ws).get("profile") or {}
    dev = prof.get("dev") or {}
    test = prof.get("test") or {}
    eff = dict(_DEV_DEFAULTS)
    pkg_over: dict[str, dict] = {}
    for layer in (dev, test):
        for k, v in layer.items():
            if k in _DEV_DEFAULTS or k in ("split-debuginfo", "strip"):
                eff[k] = v
        for name, over in (layer.get("package") or {}).items():
            pkg_over.setdefault(name, {}).update(over)
    base = _profile_flags(eff, profile_level=True)
    star = _profile_flags(pkg_over.pop("*", {}), profile_level=False)
    per_pkg = {n: _profile_flags(o, profile_level=False) for n, o in sorted(pkg_over.items())}
    return base, {n: f for n, f in per_pkg.items() if f}, star


