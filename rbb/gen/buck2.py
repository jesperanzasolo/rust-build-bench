@dataclasses.dataclass
class Edge:
    pkg_id: str
    package: str          # dependency package name
    extern: str           # name the code uses (rename applied, `-` -> `_`)
    lib_crate: str        # the dependency's own lib crate name
    kinds: set[str]       # active kinds on the host: normal/dev/build
    member: bool


@dataclasses.dataclass
class Analysis:
    ws: Workspace
    by_id: dict
    member_ids: dict[str, str]                 # package name -> id
    edges: dict[str, list[Edge]]               # member name -> active edges
    filtered: list[str]                        # "member -> dep (target)" dropped for the host
    tp_keys: dict[str, str]                    # third-party package id -> //third-party:<key>
    host_triple: str
    host_reachable: set[str] = dataclasses.field(default_factory=set)  # package ids built on the host


def _lib_crate_name(pkg: dict) -> str:
    for t in pkg["targets"]:
        if set(t["kind"]) & _LIB_KINDS:
            return t["name"].replace("-", "_")
    return pkg["name"].replace("-", "_")


def _sanitize(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]+", "-", s).strip("-")


def _active_edge(pkg: dict, features: list[str], extern: str) -> bool:
    """Is the resolve edge `pkg -> extern` activated by `pkg`'s enabled features?
    `cargo metadata` lists optional dependencies in resolve.nodes even when no enabled
    feature turns them on."""
    decls = [d for d in pkg.get("dependencies", [])
             if (d.get("rename") or d["name"]).replace("-", "_") == extern]
    if not decls or any(not d.get("optional") for d in decls):
        return True
    enabled: set[str] = set()
    fmap = pkg.get("features") or {}
    for f in features:
        enabled.add(f)
        for e in fmap.get(f, []):
            if e.startswith("dep:"):
                enabled.add(e[4:])
            elif "/" in e and "?/" not in e:
                enabled.add(e.split("/", 1)[0])
    return any((d.get("rename") or d["name"]) in enabled for d in decls)


def analyze(ws: Workspace, host_cfg: dict[str, set[str]], host_triple: str) -> Analysis:
    raw = ws.raw
    by_id = {p["id"]: p for p in raw["packages"]}
    members = set(raw["workspace_members"])
    member_ids = {by_id[i]["name"]: i for i in members}
    nodes = {n["id"]: n for n in (raw.get("resolve") or {}).get("nodes", [])}
    edges: dict[str, list[Edge]] = {}
    filtered: list[str] = []
    for name, pid in sorted(member_ids.items()):
        out = []
        for d in nodes.get(pid, {}).get("deps", []):
            dp = by_id.get(d["pkg"])
            if dp is None or d["pkg"] == pid:
                continue
            kinds: set[str] = set()
            dks = d.get("dep_kinds") or [{"kind": None, "target": None}]
            for dk in dks:
                if cfg_matches(dk.get("target"), host_cfg, host_triple):
                    kinds.add(dk.get("kind") or "normal")
                else:
                    filtered.append(f"{name} -> {dp['name']} ({dk.get('target')})")
            if not kinds:
                continue
            out.append(Edge(pkg_id=d["pkg"], package=dp["name"], extern=d["name"],
                            lib_crate=_lib_crate_name(dp), kinds=kinds, member=d["pkg"] in members))
        out.sort(key=lambda e: (e.package, e.pkg_id))
        edges[name] = out

    # Third-party alias keys: the package name, or name-version when several versions
    # of one package are direct dependencies somewhere in the workspace.
    tp_ids = sorted({e.pkg_id for es in edges.values() for e in es if not e.member})
    by_name: dict[str, list[str]] = {}
    for i in tp_ids:
        by_name.setdefault(by_id[i]["name"], []).append(i)
    tp_keys: dict[str, str] = {}
    for n, ids in sorted(by_name.items()):
        if len(ids) == 1:
            tp_keys[ids[0]] = n
            continue
        seen: set[str] = set()
        for i in sorted(ids, key=lambda i: (by_id[i]["version"], i)):
            # Not "name-version": Reindeer already names the versioned rule that way.
            key = f"{n}-{_sanitize(by_id[i]['version']).replace('.', '_')}"
            while key in seen:
                key += "-x"
            seen.add(key)
            tp_keys[i] = key
    # Packages built for the host: members, then normal/build edges whose `target`
    # matches (plus members' dev-dependencies). Reindeer reports fixups for crates it
    # never builds as unused, so only these get build-script fixups.
    reach: set[str] = set(members)
    stack = list(members)
    while stack:
        pid = stack.pop()
        feats = nodes.get(pid, {}).get("features", [])
        for d in nodes.get(pid, {}).get("deps", []):
            if not _active_edge(by_id[pid], feats, d["name"]):
                continue
            for dk in d.get("dep_kinds") or [{"kind": None, "target": None}]:
                kind = dk.get("kind") or "normal"
                if kind == "dev" and pid not in members:
                    continue
                # A build-dependency only builds if the crate has a build script; a
                # published crate may declare build-dependencies with `build = false`.
                if kind == "build" and not any("custom-build" in t["kind"]
                                               for t in by_id[pid]["targets"]):
                    continue
                if cfg_matches(dk.get("target"), host_cfg, host_triple) and d["pkg"] not in reach:
                    reach.add(d["pkg"])
                    stack.append(d["pkg"])
    return Analysis(ws=ws, by_id=by_id, member_ids=member_ids, edges=edges,
                    filtered=sorted(set(filtered)), tp_keys=tp_keys, host_triple=host_triple,
                    host_reachable=reach)


