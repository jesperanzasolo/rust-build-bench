def module_bazel(ws: Workspace, *, rust_version: str, rules_rust_version: str,
                 edition: str, platform_triples: list[str],
                 rust_sha256s: dict[str, str] | None = None,
                 cargo_bazel_lockfile: str | None = CARGO_BAZEL_LOCKFILE,
                 rules_shell_version: str = "0.6.1") -> str:
    manifests = sorted({_label(p.dir, "Cargo.toml") for p in ws.members()} | {"//:Cargo.toml"})
    sha = dict(sorted((rust_sha256s or {}).items()))
    out = [HEADER, _call("module", {"name": "rbb_corpus", "version": "0.0.0"})]
    out.append(_call("bazel_dep", {"name": "rules_rust", "version": rules_rust_version}))
    out.append(_call("bazel_dep", {"name": "rules_shell", "version": rules_shell_version}))
    out.append("\n# Rust toolchain: exactly the version the corpus' rust-toolchain.toml selects.\n")
    out.append('rust = use_extension("@rules_rust//rust:extensions.bzl", "rust")\n')
    out.append(_call("rust.toolchain", {"edition": edition, "sha256s": sha,
                                        "versions": [rust_version]}))
    out.append('use_repo(rust, "rust_toolchains")\n\n')
    out.append('register_toolchains("@rust_toolchains//:all")\n')
    out.append("\n# The cargo/rustc crate_universe resolves with: the same Rust version.\n")
    out.append('rust_host_tools = use_extension("@rules_rust//rust:extensions.bzl", "rust_host_tools")\n')
    out.append(_call("rust_host_tools.host_tools", {"name": HOST_TOOLS_REPO, "sha256s": sha,
                                                     "version": rust_version}))
    out.append(f'use_repo(rust_host_tools, "{HOST_TOOLS_REPO}")\n')
    out.append("\n# Third-party crates, resolved from the workspace's own Cargo.lock.\n")
    out.append('crate = use_extension("@rules_rust//crate_universe:extensions.bzl", "crate")\n')
    attrs = {
        "name": CRATES_REPO,
        "cargo_lockfile": "//:Cargo.lock",
        "host_tools": f"@{HOST_TOOLS_REPO}",
        "manifests": manifests,
        # Never rewrite the corpus' tracked Cargo.lock (it would look like a source change).
        "skip_cargo_lockfile_overwrite": True,
        "supported_platform_triples": sorted(platform_triples),
    }
    if cargo_bazel_lockfile:
        attrs["lockfile"] = f"//:{cargo_bazel_lockfile}"
    out.append(_call("crate.from_cargo", attrs))
    out.append(f'use_repo(crate, "{CRATES_REPO}")\n')
    return "".join(out)


def bazelrc(*, output_user_root: str, repository_cache: str, remote_cache: str | None,
            test_env: dict[str, str]) -> str:
    lines = [
        HEADER.rstrip("\n"),
        f"startup --output_user_root={output_user_root}",
        "",
        "# Downloads survive every wipe (methodology: shared download caches).",
        f"common --repository_cache={repository_cache}",
        "common --color=no",
        "common --curses=no",
        "",
        "# Cache keys must not depend on the caller's PATH or other env.",
        "build --incompatible_strict_action_env",
        "# Same rmeta pipelining Cargo does by default.",
        "build --@rules_rust//rust/settings:pipelined_compilation=True",
        "build --keep_going",
    ]
    if remote_cache:
        lines += [f"build --remote_cache={remote_cache}", "build --remote_upload_local_results"]
    lines += [
        "",
        "test --build_tests_only",
        "test --test_output=errors",
        f"test --test_timeout={TEST_TIMEOUT_S}",
        "# Cargo runs test binaries from the package directory; see rbb_test_launcher.sh.",
        f"test --run_under=//:{LAUNCHER}",
    ]
    for k, v in sorted(test_env.items()):
        lines.append(f"test --test_env={k}={v}")
    return "\n".join(lines) + "\n"


def launcher_script() -> str:
    return "#!/usr/bin/env bash\n" + HEADER + """#
# `--run_under` launcher for every rust_test. Reproduces how Cargo runs a test binary:
#   * the working directory is the package directory ($CARGO_MANIFEST_DIR);
#   * CARGO_MANIFEST_DIR and CARGO_BIN_EXE_* are absolute paths.
# rules_rust sets CARGO_MANIFEST_DIR (and our BUILD files set CARGO_BIN_EXE_*) relative
# to the runfiles root, which is Bazel's working directory for tests.
set -euo pipefail
root="$PWD"
exe="$1"
shift
case "$exe" in /*) ;; *) exe="$root/$exe" ;; esac
# insta's documented override for snapshot lookup (it would run `cargo metadata`).
export INSTA_WORKSPACE_ROOT="$root"
while IFS='=' read -r name _; do
  case "$name" in
    CARGO_BIN_EXE_*)
      val="${!name}"
      case "$val" in /*) ;; *) export "$name=$root/$val" ;; esac ;;
  esac
done < <(env)
dir="${CARGO_MANIFEST_DIR:-}"
case "$dir" in
  "") export CARGO_MANIFEST_DIR="$root" ;;
  /*) ;;
  *) export CARGO_MANIFEST_DIR="$root/$dir" ;;
esac
cd "$CARGO_MANIFEST_DIR"
exec "$exe" "$@"
"""


