"""Corpus checkout, replay-window resolution and the correctness canary.

Every tool gets its own clone of the corpus (sharing objects with one mirror), so
generated configuration from one tool can never leak into another tool's run.
"""

from __future__ import annotations

import dataclasses
import os
import re
from pathlib import Path

from .config import Corpus
from .measure import capture

GIT_ID = ["-c", "user.name=rust-build-bench", "-c", "user.email=bench@invalid",
          "-c", "commit.gpgsign=false"]


def git(ws: Path, *args: str, check: bool = True) -> str:
    return capture(["git", *GIT_ID, *args], cwd=ws, check=check).strip()


def ensure_mirror(corpus: Corpus, mirrors: Path) -> Path:
    """A bare repo holding the replay window (plus a little slack) of `corpus`."""
    if corpus.kind != "git":
        raise ValueError(f"unsupported corpus kind {corpus.kind}")
    m = mirrors / f"{corpus.name}.git"
    depth = str(corpus.replay_commits + 5)
    if not (m / "HEAD").exists():
        m.mkdir(parents=True, exist_ok=True)
        capture(["git", "init", "-q", "--bare", str(m)], cwd=mirrors)
        capture(["git", "-C", str(m), "remote", "add", "origin", corpus.repo], cwd=mirrors)
    have = capture(["git", "-C", str(m), "cat-file", "-t", corpus.commit], cwd=mirrors, check=False).strip()
    if have != "commit":
        capture(["git", "-C", str(m), "fetch", "-q", "--depth", depth, "origin", corpus.commit], cwd=mirrors)
    capture(["git", "-C", str(m), "update-ref", "refs/heads/rbb-tip", corpus.commit], cwd=mirrors)
    return m


def replay_window(mirror: Path, corpus: Corpus) -> list[str]:
    """[c0, c1, ..., cN]: c0 is the base the window starts from, cN == corpus.commit."""
    out = capture(["git", "-C", str(mirror), "rev-list", "--first-parent",
                   f"--max-count={corpus.replay_commits + 1}", corpus.commit], cwd=mirror)
    commits = list(reversed(out.split()))
    if len(commits) < corpus.replay_commits + 1:
        raise RuntimeError(f"{corpus.name}: only {len(commits)} commits available in mirror")
    return commits


def clone_for_tool(mirror: Path, ws: Path, generated_paths: tuple[str, ...]) -> None:
    if (ws / ".git").exists():
        return
    ws.parent.mkdir(parents=True, exist_ok=True)
    capture(["git", "clone", "-q", "--shared", "--no-checkout", str(mirror), str(ws)], cwd=ws.parent)
    exclude = ws / ".git" / "info" / "exclude"
    exclude.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# rust-build-bench: files generated by the tool under test"]
    lines += [p if p.startswith("/") or "*" in p else f"/{p}" for p in generated_paths]
    exclude.write_text("\n".join(lines) + "\n")


# Per-package config files some tools generate. If a crate directory disappears
# between commits, a stale one would keep the directory alive and break Cargo's
# `members = ["crates/*"]` glob, so they are removed from directories that hold no
# tracked files after checkout. The adapter's sync() regenerates them.
GENERATED_CONFIG = {"BUILD.bazel", "BUCK", "moon.yml"}
_SKIP_DIRS = {".git", "target", "buck-out", "third-party", ".moon"}


def checkout(ws: Path, commit: str) -> None:
    """Move the work tree to `commit`, keeping ignored (generated) files and build
    state, exactly as `git checkout` on a CI runner with a persistent workspace."""
    git(ws, "checkout", "-q", "--detach", "--force", commit)
    git(ws, "clean", "-q", "-fd")   # untracked, non-ignored files only
    tracked_dirs = {str(Path(f).parent) for f in git(ws, "ls-files").splitlines()}
    tracked_dirs |= {str(p) for d in list(tracked_dirs) for p in Path(d).parents}
    for dirpath, dirs, files in os.walk(ws, topdown=True):
        dirs[:] = [d for d in dirs if d not in _SKIP_DIRS and not d.startswith("bazel-")]
        rel = os.path.relpath(dirpath, ws)
        if rel == "." or rel in tracked_dirs:
            continue
        stale = [f for f in files if f in GENERATED_CONFIG]
        for f in stale:
            os.unlink(os.path.join(dirpath, f))
        if stale:
            try:
                os.removedirs(dirpath)   # removes now-empty parents too
            except OSError:
                pass


def changed_files(ws: Path, base: str, head: str) -> list[str]:
    return [l for l in git(ws, "diff", "--name-only", f"{base}..{head}").splitlines() if l]


# ---------------------------------------------------------------------------
# Correctness canary
# ---------------------------------------------------------------------------
CANARY_MARK = "RBB_CANARY_MISMATCH"
CANARY_TEST = "rbb_canary"


@dataclasses.dataclass
class CanaryStep:
    label: str
    commit: str
    expect_failure: bool


def _lib_root(ws: Path, package_dir: str) -> Path:
    for cand in ("src/lib.rs",):
        p = ws / package_dir / cand
        if p.exists():
            return p
    raise RuntimeError(f"no src/lib.rs under {package_dir}")


def make_canary_commits(ws: Path, corpus: Corpus, pkg_dirs: dict[str, str],
                        lib_names: dict[str, str]) -> list[CanaryStep]:
    """Create three commits on top of HEAD:

    K1  add `RBB_CANARY = 1` to upstream and a downstream test asserting it is 1  (pass)
    K2  change the constant to 2                                                (FAIL)
    K3  change it back to 1                                                     (pass)

    A tool that reports K2 as passing served a stale result: it did not rebuild or
    rerun the downstream test after its dependency changed.
    """
    up, down = corpus.canary.upstream, corpus.canary.downstream
    if not up or not down:
        return []
    up_root = _lib_root(ws, pkg_dirs[up])
    test_file = ws / pkg_dirs[down] / "tests" / f"{CANARY_TEST}.rs"
    test_file.parent.mkdir(parents=True, exist_ok=True)
    up_crate = lib_names[up]
    base_src = up_root.read_text()

    def set_value(v: int) -> None:
        up_root.write_text(base_src.rstrip("\n") + f"\n\n#[doc(hidden)]\npub const RBB_CANARY: u32 = {v};\n")

    set_value(1)
    test_file.write_text(
        "// Generated by rust-build-bench: correctness canary.\n"
        f"#[test]\nfn {CANARY_TEST}() {{\n"
        f"    let got = {up_crate}::RBB_CANARY;\n"
        f"    if got != 1 {{\n        panic!(\"{CANARY_MARK}: expected 1, got {{got}}\");\n    }}\n}}\n")
    steps = []
    git(ws, "add", "-A", str(up_root.relative_to(ws)), str(test_file.relative_to(ws)))
    git(ws, "commit", "-q", "-m", "rbb canary K1: add canary (expect pass)")
    steps.append(CanaryStep("K1", git(ws, "rev-parse", "HEAD"), False))
    set_value(2)
    git(ws, "commit", "-q", "-am", "rbb canary K2: change upstream constant (expect failure)")
    steps.append(CanaryStep("K2", git(ws, "rev-parse", "HEAD"), True))
    set_value(1)
    git(ws, "commit", "-q", "-am", "rbb canary K3: revert (expect pass)")
    steps.append(CanaryStep("K3", git(ws, "rev-parse", "HEAD"), False))
    return steps


_ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")


def canary_verdict(log_text: str, exit_code: int, expect_failure: bool) -> dict:
    """Did the tool report the canary correctly?

    expect_failure: the run must exit non-zero AND show the canary's panic message
    (proof the downstream test was rebuilt and executed against the new upstream).
    expect pass:    the canary's panic message must not appear.
    """
    text = _ANSI.sub("", log_text)
    seen = CANARY_MARK in text
    if expect_failure:
        ok = exit_code != 0 and seen
        reason = "detected" if ok else ("stale-pass" if exit_code == 0 else "failed-without-canary-output")
    else:
        ok = not seen
        reason = "clean" if ok else "stale-failure"
    return {"ok": ok, "reason": reason, "marker_seen": seen, "exit_code": exit_code}
