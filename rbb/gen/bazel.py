def _package_build(ws: Workspace, pkg: Package, corpus: Corpus, ctx: dict) -> tuple[str, dict]:
    excluded = pkg.name in set(corpus.exclude_packages)
    names = _Names()
    names.used |= {"cargo_toml_env_vars", ALL_FILES}
    names.used |= set(ctx["filegroups"].get(pkg.dir, {}))
    manifest = _manifest(ws, pkg)
    harness = _harness(manifest)
    features = list(pkg.features)
    dropped = sorted(ctx["dropped_features"].get(pkg.name, []))
    features = sorted(f for f in features if f not in dropped)
    feat_set = set(features)
    lib_names = ctx["lib_names"]
    platforms = ctx["ws_dep_platforms"]
    triple = ctx["host_triple"]
    cov = {"targets": [], "skipped": [], "dropped_features": dropped}

    def ws_deps(*kinds: str) -> tuple[list[str], list[str], dict[str, str]]:
        deps, pms, aliases = [], [], {}
        for d in pkg.ws_deps:
            ks = d.kinds & set(kinds)
            if not ks:
                continue
            dp = ws.packages.get(d.package)
            if dp is None or dp.lib is None:
                continue
            targets = [t for k in ks for t in platforms.get((pkg.name, d.package, k), [None])]
            if targets and all(t is not None and not cfg_matches(t, triple) for t in targets):
                continue
            lbl = _label(dp.dir, ctx["lib_target"][dp.name])
            (pms if dp.is_proc_macro else deps).append(lbl)
            if d.crate_name != dp.lib_crate_name:
                aliases[lbl] = d.crate_name
        return sorted(set(deps)), sorted(set(pms)), aliases

    ext_renamed = {k for d in pkg.ext_deps
                   for k in d.kinds
                   if d.crate_name != lib_names.get(d.package, d.package.replace("-", "_"))}

    def aliases_expr(kinds: set[str], fp_aliases: dict[str, str]):
        """`aliases(...)` for renamed third-party deps, `|` first-party renames."""
        flags = []
        if "normal" in kinds and "normal" in ext_renamed:
            flags += ["normal = True", "proc_macro = True"]
        if "dev" in kinds and "dev" in ext_renamed:
            flags += ["normal_dev = True", "proc_macro_dev = True"]
        if "build" in kinds and "build" in ext_renamed:
            flags += ["build = True", "build_proc_macro = True"]
        parts = []
        if flags:
            parts.append(f"aliases({', '.join(flags)})")
        if fp_aliases:
            parts.append(_render(dict(sorted(fp_aliases.items())), 1))
        return Expr(" | ".join(parts)) if parts else None

    out = [HEADER]
    loads = {
        "@rules_rust//rust:defs.bzl": set(),
        "@rules_rust//cargo:defs.bzl": {"cargo_toml_env_vars"},
        f"@{CRATES_REPO}//:defs.bzl": set(),
    }
    body: list[str] = []
    env_files = [":cargo_toml_env_vars"]
    lib_srcs_excl = [f"{d}/**" for d in _NON_LIB_DIRS] + ["build.rs"]
    if pkg.build_script:
        lib_srcs_excl.append(_rel(pkg, pkg.build_script.src_path))

    def srcs_for(root: str) -> Expr:
        excl = [e for e in lib_srcs_excl
                if not (root == e or (e.endswith("/**") and root.startswith(e[:-2])))]
        return _glob(["**/*.rs"], excl)

    # compile_data: files include*!() reads, in and outside the package.
    compile_data = list(_in_package_includes(ws, pkg))
    compile_data += ctx["outside_labels"].get(pkg.name, [])
    compile_data = sorted(set(compile_data))

    # -- build script ---------------------------------------------------------
    bs_label = None
    if pkg.build_script:
        bs = pkg.build_script
        bs_name = names.take(f"{pkg.name}_bs")
        bs_label = f":{bs_name}"
        b_deps, b_pms, b_alias = ws_deps("build")
        root = _rel(pkg, bs.src_path)
        srcs = [root]
        if posixpath.dirname(root) == "":
            srcs_expr = _concat(srcs, _glob(["build/**/*.rs"]))
        else:
            srcs_expr = _glob([root, posixpath.join(posixpath.dirname(root), "build/**/*.rs")])
        loads["@rules_rust//cargo:defs.bzl"].add("cargo_build_script")
        loads[f"@{CRATES_REPO}//:defs.bzl"].add("all_crate_deps")
        al = aliases_expr({"build"}, b_alias)
        if al and "aliases(" in al:
            loads[f"@{CRATES_REPO}//:defs.bzl"].add("aliases")
        body.append(_call("cargo_build_script", {
            "name": bs_name,
            "aliases": al,
            "compile_data": compile_data,
            "crate_features": features,
            "crate_name": "build_script_build",
            "crate_root": root,
            "data": [f":{ALL_FILES}"],
            "deps": _concat(Expr("all_crate_deps(build = True)"), b_deps),
            "edition": bs.edition,
            "links": pkg.links,
            "pkg_name": pkg.name,
            "proc_macro_deps": _concat(Expr("all_crate_deps(build_proc_macro = True)"), b_pms),
            "rustc_env_files": env_files,
            "srcs": srcs_expr,
            "version": pkg.version,
        }))
        cov["targets"].append({"name": bs_name, "kind": "cargo_build_script"})

    n_deps, n_pms, n_alias = ws_deps("normal")
    own = [bs_label] if bs_label else []

    # -- library ----------------------------------------------------------------
    lib_label = None
    if pkg.lib:
        lib = pkg.lib
        lib_name = ctx["lib_target"][pkg.name]
        names.used.add(lib_name)
        lib_label = f":{lib_name}"
        rule = "rust_proc_macro" if pkg.is_proc_macro else "rust_library"
        loads["@rules_rust//rust:defs.bzl"].add(rule)
        loads[f"@{CRATES_REPO}//:defs.bzl"].add("all_crate_deps")
        al = aliases_expr({"normal"}, n_alias)
        if al and "aliases(" in al:
            loads[f"@{CRATES_REPO}//:defs.bzl"].add("aliases")
        root = _rel(pkg, lib.src_path)
        body.append(_call(rule, {
            "name": lib_name,
            "aliases": al,
            "compile_data": compile_data,
            "crate_features": features,
            "crate_name": lib.crate_name,
            "crate_root": root,
            "deps": _concat(Expr("all_crate_deps(normal = True)"), n_deps + own),
            "edition": lib.edition,
            "proc_macro_deps": _concat(Expr("all_crate_deps(proc_macro = True)"), n_pms),
            "rustc_env_files": env_files,
            "srcs": srcs_for(root),
            "version": pkg.version,
            "visibility": ["//visibility:public"],
        }))
        cov["targets"].append({"name": lib_name, "kind": rule})

    lib_dep = [lib_label] if (lib_label and not pkg.is_proc_macro) else []
    lib_pm = [lib_label] if (lib_label and pkg.is_proc_macro) else []

    # -- binaries ---------------------------------------------------------------
    bins: list[tuple[Target, str]] = []
    for b in sorted(pkg.bins, key=lambda t: t.name):
        missing = sorted(set(b.required_features) - feat_set)
        if missing:
            cov["skipped"].append({"target": b.name, "kind": "bin",
                                   "reason": f"required-features not enabled: {missing}"})
            continue
        bname = names.take(b.name if b.name not in names.used else f"{b.name}_bin")
        bins.append((b, bname))
        loads["@rules_rust//rust:defs.bzl"].add("rust_binary")
        loads[f"@{CRATES_REPO}//:defs.bzl"].add("all_crate_deps")
        al = aliases_expr({"normal"}, n_alias)
        if al and "aliases(" in al:
            loads[f"@{CRATES_REPO}//:defs.bzl"].add("aliases")
        root = _rel(pkg, b.src_path)
        body.append(_call("rust_binary", {
            "name": bname,
            "aliases": al,
            "binary_name": b.name if bname != b.name else None,
            "compile_data": compile_data,
            "crate_features": features,
            "crate_name": b.crate_name,
            "crate_root": root,
            "deps": _concat(Expr("all_crate_deps(normal = True)"), n_deps + own + lib_dep),
            "edition": b.edition,
            "proc_macro_deps": _concat(Expr("all_crate_deps(proc_macro = True)"), n_pms + lib_pm),
            "rustc_env_files": env_files,
            "srcs": srcs_for(root),
            "version": pkg.version,
            "visibility": ["//visibility:public"],
        }))
        cov["targets"].append({"name": bname, "kind": "rust_binary"})

    # -- tests --------------------------------------------------------------------
    test_data = [f":{ALL_FILES}"] + ctx["extra_data_labels"].get(pkg.name, [])
    test_data = sorted(set(test_data))
    args = []
    for s in corpus.skip_tests:
        args += ["--skip", s]
    d_deps, d_pms, d_alias = ws_deps("dev")
    if excluded:
        cov["skipped"].append({"target": "*", "kind": "tests", "reason": "package in exclude_packages"})
    else:
        if pkg.lib and pkg.lib.test:
            tname = names.take(f"{ctx['lib_target'][pkg.name]}_unit_test")
            loads["@rules_rust//rust:defs.bzl"].add("rust_test")
            al = aliases_expr({"dev"}, {k: v for k, v in d_alias.items()})
            if al and "aliases(" in al:
                loads[f"@{CRATES_REPO}//:defs.bzl"].add("aliases")
            body.append(_call("rust_test", {
                "name": tname,
                "aliases": al,
                "args": args,
                "crate": lib_label,
                "crate_features": features,
                "data": test_data,
                "deps": _concat(Expr("all_crate_deps(normal_dev = True)"),
                                [d for d in d_deps if d not in n_deps]),
                "proc_macro_deps": _concat(Expr("all_crate_deps(proc_macro_dev = True)"),
                                           [d for d in d_pms if d not in n_pms]),
                "rustc_env_files": env_files,
                "use_libtest_harness": False if harness.get(("lib", "")) is False else None,
                "version": pkg.version,
            }))
            cov["targets"].append({"name": tname, "kind": "rust_test", "test": "lib"})
        for b, bname in bins:
            if not b.test:
                continue
            tname = names.take(f"{bname}_bin_unit_test")
            loads["@rules_rust//rust:defs.bzl"].add("rust_test")
            body.append(_call("rust_test", {
                "name": tname,
                "args": args,
                "crate": f":{bname}",
                "crate_features": features,
                "data": test_data,
                "deps": _concat(Expr("all_crate_deps(normal_dev = True)"),
                                [d for d in d_deps if d not in n_deps]),
                "proc_macro_deps": _concat(Expr("all_crate_deps(proc_macro_dev = True)"),
                                           [d for d in d_pms if d not in n_pms]),
                "rustc_env_files": env_files,
                "use_libtest_harness": False if harness.get(("bin", b.name)) is False else None,
                "version": pkg.version,
            }))
            cov["targets"].append({"name": tname, "kind": "rust_test", "test": f"bin:{b.name}"})
        it_roots = {t.name: _rel(pkg, t.src_path) for t in pkg.tests}
        bin_env = {f"CARGO_BIN_EXE_{b.name}": f"$(rootpath :{bname})" for b, bname in bins}
        up = "" if pkg.dir == "." else "../" * (pkg.dir.count("/") + 1)
        bin_rustc_env = {f"CARGO_BIN_EXE_{b.name}": f"{up}$(rootpath :{bname})" for b, bname in bins}
        all_deps, all_pms, all_alias = ws_deps("normal", "dev")
        for t in sorted(pkg.tests, key=lambda x: x.name):
            if not t.test:
                cov["skipped"].append({"target": t.name, "kind": "test", "reason": "test = false"})
                continue
            missing = sorted(set(t.required_features) - feat_set)
            if missing:
                cov["skipped"].append({"target": t.name, "kind": "test",
                                       "reason": f"required-features not enabled: {missing}"})
                continue
            root = it_roots[t.name]
            if root.startswith("tests/"):
                excl = []
                for other, oroot in it_roots.items():
                    if other == t.name or not oroot.startswith("tests/"):
                        continue
                    if posixpath.basename(oroot) == "main.rs" and oroot.count("/") >= 2:
                        excl.append(posixpath.dirname(oroot) + "/**")
                    else:
                        excl.append(oroot)
                if posixpath.basename(root) == "main.rs":
                    excl = [e for e in excl if not (e.endswith("/**") and root.startswith(e[:-2]))]
                srcs = _glob(["tests/**/*.rs"], excl)
            else:
                srcs = _glob([root, _dir_glob(posixpath.dirname(root)).replace("**", "**/*.rs")])
            tname = names.take(f"{t.name}_test")
            loads["@rules_rust//rust:defs.bzl"].add("rust_test")
            loads[f"@{CRATES_REPO}//:defs.bzl"].add("all_crate_deps")
            al = aliases_expr({"normal", "dev"}, all_alias)
            if al and "aliases(" in al:
                loads[f"@{CRATES_REPO}//:defs.bzl"].add("aliases")
            body.append(_call("rust_test", {
                "name": tname,
                "aliases": al,
                "args": args,
                "compile_data": compile_data,
                "crate_features": features,
                "crate_name": t.crate_name,
                "crate_root": root,
                "data": sorted(set(test_data + [f":{bn}" for _, bn in bins])),
                "deps": _concat(Expr("all_crate_deps(normal = True, normal_dev = True)"),
                                all_deps + own + lib_dep),
                "edition": t.edition,
                "env": dict(sorted(bin_env.items())),
                "proc_macro_deps": _concat(Expr("all_crate_deps(proc_macro = True, proc_macro_dev = True)"),
                                           all_pms + lib_pm),
                "rustc_env": dict(sorted(bin_rustc_env.items())),
                "rustc_env_files": env_files,
                "srcs": srcs,
                "use_libtest_harness": False if harness.get(("test", t.name)) is False else None,
                "version": pkg.version,
            }))
            cov["targets"].append({"name": tname, "kind": "rust_test", "test": f"test:{t.name}"})

    # -- files ------------------------------------------------------------------
    files_rules = [
        _call("cargo_toml_env_vars", {
            "name": "cargo_toml_env_vars",
            "src": "Cargo.toml",
            "workspace": None if pkg.dir == "." else "//:Cargo.toml",
        }),
        _call("filegroup", {
            "name": ALL_FILES,
            "srcs": _glob(["**"], ["BUILD.bazel", "target/**"]),
            "visibility": ["//visibility:public"],
        }),
    ]
    files_rules += _filegroup_rules(ctx["filegroups"].get(pkg.dir, {}))

    for path in sorted(loads):
        syms = sorted(loads[path])
        if syms:
            out.append(f"load({_q(path)}, {', '.join(_q(s) for s in syms)})\n")
    out.append("\n")
    out.append("\n".join(files_rules + body))
    return "".join(out), cov


def _filegroup_rules(fgs: dict[str, list[str]]) -> list[str]:
    rules = []
    for name in sorted(fgs):
        rules.append(_call("filegroup", {
            "name": name,
            "srcs": _glob(fgs[name]),
            "visibility": ["//visibility:public"],
        }))
    return rules


def _root_build(ws: Workspace, ctx: dict, root_pkg_build: str | None,
                has_lockfile: bool) -> str:
    exports = ["Cargo.lock", "Cargo.toml"] + ([CARGO_BAZEL_LOCKFILE] if has_lockfile else [])
    head = [
        HEADER,
        'load("@rules_shell//shell:sh_binary.bzl", "sh_binary")\n\n',
        _call("exports_files", {"visibility": ["//visibility:public"]}, positional=[sorted(exports)]),
        "\n",
        _call("sh_binary", {"name": LAUNCHER, "srcs": [LAUNCHER_SCRIPT],
                            "visibility": ["//visibility:public"]}),
    ]
    if root_pkg_build is not None:
        # The root directory is itself a Cargo package: merge its targets in.
        loads, rest = [], []
        for line in root_pkg_build.splitlines(keepends=True):
            if line.startswith("load("):
                loads.append(line)
            elif line != HEADER:
                rest.append(line)
        return "".join([head[0], head[1], *loads, "\n", *head[2:], "\n", *rest])
    tail = [
        "\n",
        _call("filegroup", {
            "name": ALL_FILES,
            "srcs": _glob(["**"], ["BUILD.bazel", "bazel-*/**", "target/**", ".git/**"]),
            "visibility": ["//visibility:public"],
        }),
    ]
    for r in _filegroup_rules(ctx["filegroups"].get(".", {})):
        tail += ["\n", r]
    return "".join(head + tail)


