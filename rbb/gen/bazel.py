def _rel(pkg: Package, repo_path: str) -> str:
    """Repo-relative path -> package-relative path."""
    return repo_path if pkg.dir == "." else posixpath.relpath(repo_path, pkg.dir)


def _label(pkg_dir: str, name: str) -> str:
    return f"//{'' if pkg_dir == '.' else pkg_dir}:{name}"


def _in_package_includes(ws: Workspace, pkg: Package) -> list[str]:
    """Package-relative files that `include*!` macros in `pkg` read from inside the
    package (files outside are handled by files_read_outside_package)."""
    root = ws.root.resolve()
    pkg_dir = (root / pkg.dir).resolve()
    out: set[str] = set()
    for dirpath, dirs, files in os.walk(pkg_dir):
        dirs[:] = sorted(d for d in dirs if d not in ("target", ".git"))
        if dirpath != str(pkg_dir) and (Path(dirpath) / "Cargo.toml").exists():
            dirs[:] = []
            continue
        for fn in files:
            if not fn.endswith(".rs"):
                continue
            path = Path(dirpath) / fn
            try:
                text = path.read_text(errors="replace")
            except OSError:
                continue
            for m in _INCLUDE_RE.finditer(text):
                rel = m.group(1)
                if "CARGO_MANIFEST_DIR" in m.group(0):
                    target = (pkg_dir / rel.lstrip("/")).resolve()
                else:
                    target = (path.parent / rel).resolve()
                try:
                    r = target.relative_to(pkg_dir)
                except ValueError:
                    continue
                if target.is_file() and not str(r).endswith(".rs"):
                    out.add(str(r).replace(os.sep, "/"))
    return sorted(out)


def _fg_name(repo_path: str) -> str:
    return "rbb_include_" + re.sub(r"[^A-Za-z0-9_]+", "_", repo_path).strip("_")


def _dir_glob(path: str) -> str:
    return f"{path}/**" if path not in ("", ".") else "**"


class _Names:
    def __init__(self):
        self.used: set[str] = set()

    def take(self, want: str) -> str:
        name, i = want, 2
        while name in self.used:
            name = f"{want}_{i}"
            i += 1
        self.used.add(name)
        return name


