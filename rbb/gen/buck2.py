class Raw(str):
    """A Starlark expression emitted verbatim (e.g. a glob() call)."""


def _sstr(s: str) -> str:
    s = "".join(ch for ch in s if ch in "\n\t" or ord(ch) >= 0x20)
    return json.dumps(s, ensure_ascii=False)


def _arg(s: str) -> str:
    """Escape a literal for an attrs.arg() value: `$(` would start a string macro."""
    return s.replace("$(", "\\$(")


def _fmt(v, indent: int = 4) -> str:
    pad = " " * indent
    if isinstance(v, Raw):
        return str(v)
    if isinstance(v, bool):
        return "True" if v else "False"
    if isinstance(v, str):
        return _sstr(v)
    if isinstance(v, int):
        return str(v)
    if isinstance(v, (list, tuple)):
        if not v:
            return "[]"
        if len(v) == 1 and len(_fmt(v[0], indent)) < 60 and "\n" not in _fmt(v[0], indent):
            return f"[{_fmt(v[0], indent)}]"
        inner = "".join(f"{pad}    {_fmt(x, indent + 4)},\n" for x in v)
        return f"[\n{inner}{pad}]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        inner = "".join(f"{pad}    {_sstr(k)}: {_fmt(x, indent + 4)},\n" for k, x in v.items())
        return f"{{\n{inner}{pad}}}"
    raise TypeError(type(v))


def _rule(kind: str, name: str, attrs: dict) -> str:
    lines = [f"{kind}(", f"    name = {_sstr(name)},"]
    for k in sorted(attrs):
        v = attrs[k]
        if v is None or (isinstance(v, (list, dict)) and not v and k != "srcs"):
            continue
        lines.append(f"    {k} = {_fmt(v)},")
    lines.append(")")
    return "\n".join(lines)


def _glob(include: list[str], exclude: list[str] | None = None) -> Raw:
    if exclude:
        return Raw(f"glob({_fmt(include, 4)}, exclude = {_fmt(exclude, 4)})")
    return Raw(f"glob({_fmt(include, 4)})")


def _tstr(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _tval(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return _tstr(v)
    if isinstance(v, list):
        return "[" + ", ".join(_tval(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{_tstr(k)} = {_tval(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


