# ---------------------------------------------------------------------------
# Starlark rendering
# ---------------------------------------------------------------------------

class Expr(str):
    """A Starlark expression emitted verbatim (e.g. `all_crate_deps(...)`)."""


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _render(v, indent: int = 1) -> str:
    pad = "    " * indent
    if isinstance(v, Expr):
        return str(v)
    if isinstance(v, bool):
        return "True" if v else "False"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return _q(v)
    if isinstance(v, (list, tuple)):
        if not v:
            return "[]"
        if len(v) == 1 and not isinstance(v[0], (list, dict)):
            return f"[{_render(v[0], indent)}]"
        inner = "".join(f"{pad}    {_render(x, indent + 1)},\n" for x in v)
        return f"[\n{inner}{pad}]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        inner = "".join(f"{pad}    {_render(k, indent + 1)}: {_render(val, indent + 1)},\n"
                        for k, val in v.items())
        return f"{{\n{inner}{pad}}}"
    raise TypeError(f"cannot render {v!r}")


def _call(fn: str, attrs: dict, *, positional: list | None = None) -> str:
    """Render `fn(name = ..., <other attrs alphabetically>)`, dropping None/empty."""
    items = [(k, v) for k, v in attrs.items() if v is not None and v != [] and v != {}]
    items.sort(key=lambda kv: (kv[0] != "name", kv[0]))
    lines = [f"    {_render(p)}," for p in (positional or [])]
    lines += [f"    {k} = {_render(v)}," for k, v in items]
    return f"{fn}(\n" + "\n".join(lines) + "\n)\n"


def _glob(include: list[str], exclude: list[str] | None = None) -> Expr:
    parts = [_render(sorted(set(include)), 1)]
    if exclude:
        parts.append(f"exclude = {_render(sorted(set(exclude)), 1)}")
    parts.append("allow_empty = True")
    return Expr(f"glob({', '.join(parts)})")


def _concat(*parts) -> Expr | list:
    """`a + b + [...]` for Starlark, skipping empty lists."""
    out = []
    for p in parts:
        if isinstance(p, list):
            if p:
                out.append(_render(sorted(set(p)), 1))
        elif p:
            out.append(str(p))
    if not out:
        return []
    return Expr(" + ".join(out))


